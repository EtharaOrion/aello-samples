def measure(unreachable_seconds):
    """Mean bar-gated wall clock over the attempt's graded configurations, in seconds.

    The elapsed is the HARNESS measurement, never the submission's own: red line 7 is reporting an
    elapsed the host did not measure, and an axis that read the agent's number would be grading
    the declaration it exists to distrust.

    A configuration whose gate did not clear contributes the ramp's slow anchor rather than its
    own elapsed. That ordering is the gate: a run that missed its bar, broke the sibling gap,
    exceeded the ceiling or exported something inadmissible cannot buy the ramp by being fast, and
    a fast wrong run is worth what the slowest right one is worth and no more.
    """
    blocks = graded_blocks()
    if not blocks:
        raise ConstantUnmeasured(
            "the harness recorded no graded configuration; there is no wall clock to grade")
    seconds = []
    for block in blocks:
        if token(block.get("gate")) != CLEARED_GATE:
            seconds.append(float(unreachable_seconds))
            continue
        elapsed = numeric(block.get("elapsed_s"))
        if elapsed is None or elapsed <= 0:
            raise ConstantUnmeasured(
                "configuration %s cleared its gate and carries no measured wall clock"
                % block.get("config_id"))
        seconds.append(elapsed)
    return sum(seconds) / len(seconds)


def ramp(seconds, floor, knee):
    """The published descending logarithmic ramp, clipped into the unit interval.

    Logarithmic because the reward map is: halving a 240 s run is worth what halving a 120 s one
    is, and a linear ramp on seconds would price the first second saved at the ceiling the same as
    the last one saved at the knee.
    """
    if floor is None or knee is None or floor <= 0 or knee <= 0 or floor <= knee:
        return 0.0
    span = math.log(floor) - math.log(knee)
    return max(0.0, min(1.0, (math.log(floor) - math.log(max(seconds, 1e-9))) / span))

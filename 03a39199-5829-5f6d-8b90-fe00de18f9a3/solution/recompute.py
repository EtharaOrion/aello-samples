def roster_literal(roster, per_line=6):
    """A deterministic, readable Python tuple literal for the configuration roster."""
    rows, row = [], []
    for name in roster:
        row.append(repr(str(name)))
        if len(row) == per_line:
            rows.append("    " + ", ".join(row) + ",")
            row = []
    if row:
        rows.append("    " + ", ".join(row) + ",")
    return "(\n" + "\n".join(rows) + "\n)"


def sorted_map(mapping):
    """A dict rebuilt in sorted key order, so its repr is stable across regenerations."""
    return dict((k, mapping[k]) for k in sorted(mapping))


def naive_dump_bytes(layout):
    """The size of the whole table written the obvious way, at full float precision.

    Measured rather than asserted, because the 2,048-byte cap is only a design pressure if the
    naive encoding actually overruns it. If a later edit widened the cap or narrowed the family
    until a raw dump fitted, CTL-NAIVE-DUMP would be measuring nothing and this generator would
    be emitting a check with no teeth. validate() refuses that.
    """
    schema = layout["carry_schema"]
    entry = dict((f, 0.12345678901234567) for f in schema["scalar_fields"])
    entry[schema["src_field"]] = schema["src_observed"]
    table = dict((config_id, entry) for config_id in layout["config_roster"])
    return len(json.dumps(table, sort_keys=True).encode("utf-8"))


def gcd(a, b):
    while b:
        a, b = b, a % b
    return a


def schedule_visits(layout, through_attempt):
    """config_id -> last scheduled visit at or before through_attempt, from the published rule."""
    schedule = layout["attempt_schedule"]
    roster = layout["config_roster"]
    table = {}
    for attempt in range(1, int(through_attempt) + 1):
        for offset in schedule["offsets"]:
            table[roster[(schedule["stride"] * attempt + offset) % schedule["modulus"]]] = attempt
    return table


def validate(grounding):
    """Refuse a grounding this generator cannot honestly compile.

    The refusals are this slot's own: a memory channel that does not bind, a schedule that does
    not reach every configuration, a time to live that does not actually expire the eight
    configurations the scored attempt is graded on. Each of those would leave a check in the
    emitted module asserting something no longer true of the design, which is worse than no check.
    """
    problems = []
    items = grounding["items"]
    ids = [i["id"] for i in items]
    if len(set(ids)) != len(ids):
        problems.append("duplicate item ids: %r" % sorted(set(x for x in ids if ids.count(x) > 1)))
    for item in items:
        if frozenset(item) != ITEM_SCHEMA:
            problems.append("item %r does not carry the closed item schema" % item.get("id"))
            continue
        if item["outcome_class"] not in OUTCOME_CLASSES:
            problems.append("item %r has outcome_class %r" % (item["id"], item["outcome_class"]))
        if item["evaluation_target"] not in grounding["evaluation_target_vocabulary"]:
            problems.append("item %r evaluates %r, which the vocabulary does not admit"
                            % (item["id"], item["evaluation_target"]))
        if not isinstance(item["weight"], int) or item["weight"] <= 0:
            problems.append("item %r carries weight %r" % (item["id"], item["weight"]))
        if item["mode"] != "compiled":
            problems.append("item %r is %r; this slot compiles every item"
                            % (item["id"], item["mode"]))
    targets = set(i["evaluation_target"] for i in items)
    for required in ("submitted_program", "proposed_carry_store", "harness_attempt_record"):
        if required not in targets:
            problems.append("no item evaluates %r, and this slot grades a program, a memory "
                            "channel and a host measurement" % required)
    unused = sorted(set(grounding["evaluation_target_vocabulary"]) - targets)
    if unused:
        problems.append("the vocabulary admits %s, which no item evaluates" % unused)
    outcome = [i["id"] for i in items if i["dimension"] == "outcome"]
    if len(outcome) != 1:
        problems.append("expected exactly one outcome item, found %r" % outcome)
    for name in RAMP:
        if grounding["constants"].get(name) is not None:
            problems.append("constant %r is authored at Phase 0; it is measured, not authored"
                            % name)

    layout = grounding.get("corpus_layout") or {}
    roster = layout.get("config_roster") or []
    count = layout.get("configuration_count")
    if len(roster) != count or len(set(roster)) != len(roster):
        problems.append("the configuration roster carries %d identifiers against a declared "
                        "count of %r, or repeats one" % (len(roster), count))
    schedule = layout.get("attempt_schedule") or {}
    for key in SCHEDULE_KEYS:
        if key not in schedule:
            problems.append("the attempt schedule does not publish %r" % key)
    if not problems:
        offsets = list(schedule["offsets"])
        modulus = int(schedule["modulus"])
        final = int(schedule["final_attempt"])
        wanted = int(schedule["final_attempt_configurations"])
        if modulus != len(roster):
            problems.append("the schedule's modulus %d is not the roster size %d"
                            % (modulus, len(roster)))
        if len(set(o % modulus for o in offsets)) != len(offsets):
            problems.append("the schedule's offsets collide modulo the roster size, so an "
                            "attempt would grade the same configuration twice")
        if len(offsets) != int(schedule["graded_per_attempt"]):
            problems.append("the schedule grades %d configurations an attempt but publishes %d "
                            "offsets" % (int(schedule["graded_per_attempt"]), len(offsets)))
        if gcd(int(schedule["stride"]), modulus) != 1:
            problems.append("the schedule's stride %d is not coprime with %d, so it never "
                            "reaches every configuration" % (int(schedule["stride"]), modulus))
        visits = schedule_visits(layout, final - 1)
        unvisited = sorted(set(roster) - set(visits))
        if unvisited:
            problems.append("the schedule never visits %s before the scored attempt" % unvisited)
        ranked = sorted(visits.items(), key=lambda kv: (kv[1], kv[0]))
        if wanted >= len(roster) or wanted < 1:
            problems.append("the scored attempt grades %d of %d configurations"
                            % (wanted, len(roster)))
        else:
            # The eight oldest must actually be stale. If the time to live outlived the gap
            # between a configuration's last scheduled visit and the scored attempt, the memory
            # would survive on the schedule alone and the archetype's decay would be decorative.
            oldest_age = final - ranked[0][1]
            youngest_of_the_eight = final - ranked[wanted - 1][1]
            if youngest_of_the_eight <= int(layout["carry_ttl_attempts"]):
                problems.append(
                    "the scored attempt's %d oldest-visited configurations are at most %d "
                    "attempts stale against a time to live of %d, so no entry ever expires on "
                    "the graded half of the table"
                    % (wanted, youngest_of_the_eight, int(layout["carry_ttl_attempts"])))
            if oldest_age < youngest_of_the_eight:
                problems.append("the oldest-visited ranking is inverted")
    schema = layout.get("carry_schema") or {}
    for key in CARRY_SCHEMA_KEYS:
        if key not in schema:
            problems.append("the carry schema does not publish %r" % key)
    if not problems:
        fields = list(schema["scalar_fields"])
        if len(fields) != 6 or len(set(fields)) != 6:
            problems.append("the carry schema names %d scalar fields; the design binds six "
                            "per-configuration constants" % len(fields))
        if schema["src_observed"] == schema["src_predicted"]:
            problems.append("the src field's two values are the same value")
        if schema["stamp_field"] not in list(schema["forbidden_fields"]):
            problems.append("the stamp field %r is not forbidden to the agent, and it is the one "
                            "field only the verifier may write" % schema["stamp_field"])
        if sorted(layout["carry_field_tolerances"]) != sorted(fields):
            problems.append("the per-field tolerances do not name exactly the six scalars")
        if any(numeric_or_none(v) is None or v < 0
               for v in layout["carry_field_tolerances"].values()):
            problems.append("a per-field tolerance is negative or is not a number")
        naive = naive_dump_bytes(layout)
        if naive <= int(schema["max_bytes"]):
            problems.append("the whole table dumps to %d bytes against a cap of %d, so the "
                            "channel does not bind and CTL-NAIVE-DUMP measures nothing"
                            % (naive, int(schema["max_bytes"])))
        if not schema["scale_min"] < schema["scale_max"]:
            problems.append("the published crop-scale band is empty")
    if tuple(layout.get("lifecycle_order") or ()) != ("validate", "stamp", "expire", "persist",
                                                      "report"):
        problems.append("the carry lifecycle order is %r; stamping after expiry would revive an "
                        "entry the rule had just dropped" % (layout.get("lifecycle_order"),))
    for key in ("carry_ttl_attempts", "timer_epsilon_s", "sibling_gap_max"):
        value = numeric_or_none(layout.get(key))
        if value is None or value <= 0:
            problems.append("%s is %r; it bounds a check and has to be a positive number"
                            % (key, layout.get(key)))
    gates = list(layout.get("gate_outcomes") or ())
    for key in ("cleared_gate", "below_bar_gate", "sibling_gap_gate"):
        if layout.get(key) not in gates:
            problems.append("%s is %r, which the published gate roster does not carry"
                            % (key, layout.get(key)))
    return problems


def numeric_or_none(value):
    if isinstance(value, bool) or value is None:
        return None
    try:
        return float(value)
    except (TypeError, ValueError):
        return None


def main():
    g = load_grounding()
    # The family validator runs FIRST and refuses rather than emitting: a generator that writes a
    # carrier it knows is malformed hands the drift check a moving target.
    problems = validate(g)
    if problems:
        raise SystemExit("AELLO-C8-S2 grounding is not well-formed: " + "; ".join(problems))

    layout = g["corpus_layout"]
    schema = layout["carry_schema"]
    schedule = layout["attempt_schedule"]
    outcome_id = [i["id"] for i in g["items"] if i["dimension"] == "outcome"][0]
    subst = {
        "slot_id": SLOT_ID,
        "outcome_id": outcome_id,
        "path": g["deliverable"]["path"],
        "proposed_carry": layout["proposed_carry_store"],
        "delivered_carry": layout["delivered_carry_store"],
        "canonical_carry": layout["canonical_carry_state"],
        "run_record": layout["run_record"],
        "reward_log": layout["reward_log"],
        "config_roster": roster_literal(layout["config_roster"]),
        "configuration_count": int(layout["configuration_count"]),
        "launch_flags": tuple(layout["launch_flags"]),
        "stride": int(schedule["stride"]),
        "offsets": tuple(schedule["offsets"]),
        "modulus": int(schedule["modulus"]),
        "graded_per_attempt": int(schedule["graded_per_attempt"]),
        "final_attempt": int(schedule["final_attempt"]),
        "final_attempt_configurations": int(schedule["final_attempt_configurations"]),
        "carry_max_bytes": int(schema["max_bytes"]),
        "scalar_fields": tuple(schema["scalar_fields"]),
        "src_field": schema["src_field"],
        "src_observed": int(schema["src_observed"]),
        "src_predicted": int(schema["src_predicted"]),
        "tag_field": schema["optional_tag_field"],
        "tag_max_bytes": int(schema["tag_max_bytes"]),
        "stamp_field": schema["stamp_field"],
        "flip_values": tuple(schema["flip_values"]),
        "off_min": int(schema["off_min"]),
        "off_max": int(schema["off_max"]),
        "scale_min": float(schema["scale_min"]),
        "scale_max": float(schema["scale_max"]),
        "rho_min": float(schema["rho_min"]),
        "amb_min": float(schema["amb_min"]),
        "amb_max": float(schema["amb_max"]),
        "tolerances": sorted_map(layout["carry_field_tolerances"]),
        "carry_ttl": int(layout["carry_ttl_attempts"]),
        "lifecycle_order": tuple(layout["lifecycle_order"]),
        "block_keys": tuple(layout["block_keys"]),
        "gate_outcomes": tuple(layout["gate_outcomes"]),
        "cleared_gate": layout["cleared_gate"],
        "below_bar_gate": layout["below_bar_gate"],
        "sibling_gap_gate": layout["sibling_gap_gate"],
        "hard_gates": tuple(sorted(set(layout["gate_outcomes"])
                                   - set([layout["cleared_gate"], layout["below_bar_gate"],
                                          layout["sibling_gap_gate"]]))),
        "sibling_gap_max": float(layout["sibling_gap_max"]),
        "timer_epsilon": float(layout["timer_epsilon_s"]),
        "log_accuracy": float(layout["log_tolerances"]["accuracy"]),
        "log_elapsed_fraction": float(layout["log_tolerances"]["elapsed_fraction"]),
        "source_limits": sorted_map(layout["source_limits"]),
        "seed_epsilon": float(layout["seed_divergence_epsilon"]),
        "budget_keys": tuple(layout["budget_keys"]),
        "guarded_writes": tuple(layout["guarded_writes"]),
    }

    # EVERY compiled item carries a written body, and the generator REFUSES when one does not.
    # The generic obligation lookup that used to stand here read a run-record key nothing writes,
    # so an item falling through to it consulted nothing and reported that it had passed.
    bodies = dict(BODIES)
    for it in g["items"]:
        if it["mode"] == "compiled" and it["id"] not in bodies:
            raise SystemExit("AELLO-C8-S2: no body written for compiled item %r; the generator "
                             "refuses rather than emitting a check that consults nothing"
                             % it["id"])
    stray = sorted(set(bodies) - set(i["id"] for i in g["items"]))
    if stray:
        raise SystemExit("AELLO-C8-S2: bodies %s belong to no item in the grounding" % stray)
    # The outcome check must SAY the slot is unmeasurable before it reads anything. Reading the
    # record first lets a missing-file failure mask the unmeasured signal, and the verifier then
    # reports gradeable=true with r_det=0.0. seed/build/freeze_batch.py refuses that bundle.
    statements = [ln.strip() for ln in bodies[outcome_id].splitlines()
                  if ln.strip() and not ln.strip().startswith("#")]
    if not statements or statements[0] != REQUIRE_FIRST:
        raise SystemExit("AELLO-C8-S2: %r must call require_measured as its first statement, "
                         "before it reads the attempt record" % outcome_id)

    tests_dir = os.path.join(BUNDLE, "tests")
    os.makedirs(tests_dir, exist_ok=True)

    # solution/TRUTH.md and solution/rubrics.json are PRIVATE_CARRIERS: seed/identity.py plants a
    # canary block into them at freeze, and canary normalisation is what keeps planting from
    # moving identity. A generator that rewrote them plainly would DROP the planted tripwire, and
    # the next content_hash would differ from the frozen one. So the planted block is carried
    # across the regeneration rather than recreated.
    truth_path = os.path.join(HERE, "TRUTH.md")
    truth = build_truth(g, TITLE).rstrip("\n") + "\n"
    keep = None
    if os.path.exists(truth_path):
        import re as _re
        m = _re.search(r"<!-- AELLO-CANARY-BLOCK.*?-->\n?", open(truth_path).read(), _re.S)
        keep = m.group(0) if m else None
    with open(truth_path, "w") as fh:
        fh.write(truth + ("\n" + keep if keep else ""))

    rub_path = os.path.join(HERE, "rubrics.json")
    rub = build_rubrics(g, ITEM_KEYS)
    if os.path.exists(rub_path):
        try:
            prev = json.load(open(rub_path))
            if "canary" in prev:
                rub["canary"] = prev["canary"]
        except Exception:
            pass
    with open(rub_path, "w") as fh:
        json.dump(rub, fh, indent=1, sort_keys=True)
        fh.write("\n")
    with open(os.path.join(tests_dir, "rubrics.json"), "w") as fh:
        json.dump(build_rubrics(g, ITEM_KEYS), fh, indent=1, sort_keys=True)
        fh.write("\n")
    with open(os.path.join(tests_dir, "test_output.py"), "w") as fh:
        # The tail arrives FINAL and is NOT substituted: it is family-shaped, it has already
        # resolved every placeholder it owns, and it legitimately contains percent signs of its
        # own, so formatting it a second time raises TypeError. Only the prelude is substituted.
        fh.write(build_tests(g, PRELUDE % subst, bodies) + TAIL)
    with open(os.path.join(tests_dir, "constants.json"), "w") as fh:
        json.dump(g["constants"], fh, indent=1, sort_keys=True)
        fh.write("\n")
    # ORDER MATTERS. `with open(path, "w")` truncates BEFORE its body's arguments are evaluated,
    # so calling read_identity() inside the with-statement reads the file this line just emptied
    # and writes nulls over the frozen identity. Read first, then open.
    prov = build_provenance(g, read_identity(HERE))
    with open(os.path.join(HERE, "provenance.yaml"), "w") as fh:
        # MATCH seed/build/screen_bind.py and the frozen generators exactly: sort_keys=True,
        # default_flow_style=False, width=100. The screen writes this carrier after the freeze,
        # so a generator using a different dump convention reorders the keys on the next
        # regeneration and reports as drift even though no value changed.
        yaml.safe_dump(prov, fh, sort_keys=True, default_flow_style=False, width=100,
                       allow_unicode=True)
    return 0



def confusion_cells(rows):
    """The nine cells as integers, keyed "human>emitted".

    Steps beyond the shorter of the two vectors are not counted. A length mismatch is its own
    check with its own knockout, and it must not leak in here as a silent truncation that
    nobody reported.
    """
    cells = dict(("%s>%s" % (human, emitted), 0) for human in LABELS for emitted in LABELS)
    for row in rows:
        for human, emitted in zip(row["human"], row["emitted"]):
            key = "%s>%s" % (human, emitted)
            if key in cells:
                cells[key] += 1
    return cells


def class_scores(cells):
    """Precision, recall and F1 per class, plus each class's emitted and human support."""
    out = {}
    for label in LABELS:
        hit = cells["%s>%s" % (label, label)]
        emitted_total = sum(cells["%s>%s" % (human, label)] for human in LABELS)
        human_total = sum(cells["%s>%s" % (label, emitted)] for emitted in LABELS)
        precision = hit / float(emitted_total) if emitted_total else 0.0
        recall = hit / float(human_total) if human_total else 0.0
        f1 = (2 * precision * recall / (precision + recall)) if (precision + recall) else 0.0
        out[label] = {"precision": round(precision, 6), "recall": round(recall, 6),
                      "f1": round(f1, 6), "emitted": emitted_total, "human": human_total}
    return out


def macro_f1(cells):
    """The flat mean of the three per-class F1 terms. Three, including the middle class."""
    scores = class_scores(cells)
    return sum(scores[label]["f1"] for label in LABELS) / float(len(LABELS))


def decisive(label):
    """The two-valued reading a collapsed pipeline is really working in."""
    return BAD if label == BAD else GOOD


def binary_step_accuracy(cells):
    """Step accuracy after folding neutral into good.

    Reported beside macro-F1 wherever the neutral class is in question, because a run that has
    collapsed the middle class reads respectably here and poorly there, and the pair of numbers
    is what makes the collapse legible.
    """
    hit = total = 0
    for human in LABELS:
        for emitted in LABELS:
            count = cells["%s>%s" % (human, emitted)]
            total += count
            if decisive(human) == decisive(emitted):
                hit += count
    return hit / float(total) if total else 0.0


def localization_breakdown(rows):
    """The four ways an emitted index can meet a human one, counted separately.

    both_sentinel and both_indexed_equal are matches. kind_mismatch -- one side the sentinel and
    the other a position -- is a miss, always: -1 is a class on this axis and never a wildcard,
    and treating it as compatible with any index would convert the whole no-error population,
    which is large on a step-level process corpus, into free score.
    """
    out = {"both_sentinel": 0, "both_indexed_equal": 0, "both_indexed_unequal": 0,
           "kind_mismatch": 0, "unusable_index": 0, "offsets": []}
    for row in rows:
        emitted, human = row["emitted_index"], row["human_index"]
        if emitted is None or isinstance(human, bool) or not isinstance(human, int):
            out["unusable_index"] += 1
        elif emitted == SENTINEL and human == SENTINEL:
            out["both_sentinel"] += 1
        elif emitted == SENTINEL or human == SENTINEL:
            out["kind_mismatch"] += 1
        elif emitted == human:
            out["both_indexed_equal"] += 1
            out["offsets"].append(0)
        else:
            out["both_indexed_unequal"] += 1
            out["offsets"].append(emitted - human)
    out["matched"] = out["both_sentinel"] + out["both_indexed_equal"]
    out["total"] = len(rows)
    return out


def localization_rate(rows):
    breakdown = localization_breakdown(rows)
    return breakdown["matched"] / float(breakdown["total"]) if breakdown["total"] else 0.0


def joint_quality(rows):
    """The mean of macro-F1 and the exact-match localisation rate.

    Formed the same way on both private shards, so the sibling gap compares like with like.
    """
    return (macro_f1(confusion_cells(rows)) + localization_rate(rows)) / 2.0


def neutral_rate_table(rows):
    """Per stratum: the emitted and the human neutral step counts, their rates and the gap."""
    table = {}
    for row in rows:
        cell = table.setdefault(str(row["stratum"]),
                                {"stratum": str(row["stratum"]), "steps": 0,
                                 "emitted_neutral": 0, "human_neutral": 0})
        for human, emitted in zip(row["human"], row["emitted"]):
            cell["steps"] += 1
            cell["emitted_neutral"] += int(emitted == NEUTRAL)
            cell["human_neutral"] += int(human == NEUTRAL)
    for cell in table.values():
        steps = float(cell["steps"]) if cell["steps"] else 1.0
        cell["emitted_rate"] = round(cell["emitted_neutral"] / steps, 6)
        cell["human_rate"] = round(cell["human_neutral"] / steps, 6)
        cell["deviation"] = round(abs(cell["emitted_rate"] - cell["human_rate"]), 6)
    return [table[key] for key in sorted(table)]


def subgroup(rows, flag):
    """One of the two floored subgroups, with the sentinel share it was answered with."""
    members = [row for row in rows if row[flag]]
    if not members:
        return None
    sentinel = sum(1 for row in members if row["emitted_index"] == SENTINEL)
    return {"flag": flag, "size": len(members),
            "matched": localization_breakdown(members)["matched"],
            "rate": localization_rate(members),
            "sentinel_share": round(sentinel / float(len(members)), 6)}


def graded_seconds():
    """t: the harness's integer seconds, ceil of the interval it timed. Never the agent's."""
    record = run_record()
    start, end = record.get("first_data_touch_ns"), record.get("artefacts_written_ns")
    if isinstance(start, bool) or isinstance(end, bool):
        return None
    if not isinstance(start, int) or not isinstance(end, int) or end < start:
        return None
    return -(-(end - start) // 10 ** 9)



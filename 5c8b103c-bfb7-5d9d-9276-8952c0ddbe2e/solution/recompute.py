def load_submission():
    """The coupled deliverable: one label sequence and one first-error index per solution."""
    with open(SUBMISSION) as handle:
        doc = json.load(handle)
    if not isinstance(doc, dict):
        raise ValueError("the deliverable must be a JSON object, not a %s" % type(doc).__name__)
    ids, outputs = doc.get("ids"), doc.get("outputs")
    if not isinstance(ids, list):
        raise ValueError("the deliverable carries no ids list")
    if not isinstance(outputs, list):
        raise ValueError("the deliverable carries no outputs list")
    if len(ids) != len(outputs):
        raise ValueError("ids carries %d entries and outputs carries %d" % (len(ids), len(outputs)))
    return doc


def submitted_records():
    """(solution id, record) in the order the artifact shipped them.

    That is the run's own presentation order, which is privately permuted per graded run. It is
    read here so one check can prove the graded counts do not depend on it; every other reader
    goes through the canonical sorted order instead.
    """
    try:
        doc = load_submission()
    except Exception:
        return []
    return [(str(i), r) for i, r in zip(doc["ids"], doc["outputs"])]


def label_sequence(record):
    if not isinstance(record, dict):
        return None
    sequence = record.get(LABELS_KEY)
    return sequence if isinstance(sequence, list) else None


def emitted_index(record):
    """The index as an EXACT integer.

    A bool is refused rather than coerced: True == 1 compares equal to step one, so a record
    carrying True would be read as naming the second step as its first error and would be graded
    against a human index it never meant.
    """
    if not isinstance(record, dict):
        return None
    value = record.get(INDEX_KEY)
    if isinstance(value, bool) or not isinstance(value, int):
        return None
    return value


def first_bad_position(sequence):
    """The position of the first bad label in a vector, or the no-error sentinel."""
    for position, label in enumerate(sequence):
        if label == BAD:
            return position
    return SENTINEL


def prefix_divergences(records):
    """Solutions whose emitted index is not the first bad position of their OWN vector.

    No human label is consulted. This is the coupling of the two emitted outputs to each other,
    which is what separates one monotone decode from two heads reconciled afterwards.
    """
    out = []
    for solution_id, record in records:
        sequence = label_sequence(record)
        index = emitted_index(record)
        if sequence is None or index is None:
            out.append({"id": solution_id, "emitted_index": index, "first_bad": None,
                        "why": "output_unreadable"})
            continue
        expected = first_bad_position(sequence)
        if index != expected:
            before = sequence[:index] if index >= 0 else []
            out.append({"id": solution_id, "emitted_index": index, "first_bad": expected,
                        "bad_before_index": sum(1 for label in before if label == BAD),
                        "why": "index_is_not_the_first_bad_label"})
    return out


def shard_rows(manifest_name, labels_name):
    """One row per solution present in the submission AND in that shard, canonical id order.

    Canonical means sorted by solution id. The held-out solutions are privately permuted per
    graded run, so a positional prior sees a different sequence every time while every integer
    count taken here runs over the same order every time.
    """
    manifest = read_json(heldout(manifest_name))
    labels = read_json(heldout(labels_name))
    if not isinstance(manifest, dict) or not isinstance(labels, dict):
        return None
    emitted = dict(submitted_records())
    rows = []
    for solution_id in sorted(set(manifest) & set(labels) & set(emitted)):
        record = emitted[solution_id]
        human = labels[solution_id]
        entry = manifest[solution_id]
        sequence = label_sequence(record)
        if sequence is None or not isinstance(human, dict) or not isinstance(entry, dict):
            continue
        rows.append({"id": solution_id,
                     "emitted": sequence,
                     "emitted_index": emitted_index(record),
                     "human": human.get(LABELS_KEY) or [],
                     "human_index": human.get(INDEX_KEY),
                     "stratum": entry.get("stratum"),
                     "step_count": entry.get("step_count"),
                     "long_solution": bool(entry.get("long_solution")),
                     "correct_answer_bad_step": bool(entry.get("correct_answer_bad_step"))})
    return rows



def validate(grounding):
    """Refuse on a malformed derivation source rather than emitting a checker from one.

    These are the invariants the emitted checker actually depends on. A generator that writes a
    carrier it knows is malformed hands the drift check a moving target.
    """
    problems = []
    items = grounding.get("items") or []
    if not items:
        problems.append("no items to compile")
    seen = set()
    for item in items:
        iid = item.get("id", "<unnamed>")
        if iid in seen:
            problems.append("duplicate item id %r" % iid)
        seen.add(iid)
        if set(item) != ITEM_SCHEMA:
            problems.append("item %r does not carry the closed schema: %s"
                            % (iid, sorted(set(item) ^ ITEM_SCHEMA)))
            continue
        if item["outcome_class"] not in OUTCOME_CLASSES:
            problems.append("item %r has outcome_class %r" % (iid, item["outcome_class"]))
        if item["evaluation_target"] not in grounding["evaluation_target_vocabulary"]:
            problems.append("item %r evaluates %r, which the vocabulary does not admit"
                            % (iid, item["evaluation_target"]))
        if not isinstance(item["weight"], int) or item["weight"] <= 0:
            problems.append("item %r carries weight %r" % (iid, item["weight"]))

    outcome = [i["id"] for i in items if i.get("dimension") == "outcome"]
    if len(outcome) != 1:
        problems.append("expected exactly one outcome item, found %r" % outcome)

    for name in RAMP:
        if grounding["constants"].get(name) is not None:
            problems.append("constant %r is authored at Phase 0; it is measured, not authored"
                            % name)

    if grounding["deliverable"].get("kind") != "json":
        problems.append("the graded deliverable of this slot is a json object carrying two "
                        "coupled outputs per solution, not %r"
                        % grounding["deliverable"].get("kind"))

    layout = grounding.get("corpus_layout") or {}
    labels = layout.get("label_vocabulary") or []
    # THREE classes, and the middle one is the whole task. A two-valued vocabulary would make the
    # neutral band, the live-neutral-row item and the abstention reading of AR7 all vacuous.
    if len(labels) != 3 or len(set(labels)) != 3:
        problems.append("the step label vocabulary is %r; this slot grades three human classes"
                        % (labels,))
    if layout.get("no_error_sentinel") in labels:
        problems.append("the no-error sentinel %r is also a step label; it is a value on the "
                        "index axis and must not be one on the label axis"
                        % layout.get("no_error_sentinel"))
    strata = layout.get("strata") or []
    if len(strata) < 2 or len(set(strata)) != len(strata):
        problems.append("the disclosed strata are %r; a per-stratum band needs at least two "
                        "distinct strata to say anything a global rate does not" % (strata,))
    stages = layout.get("timed_stages") or []
    if len(set(stages)) != len(stages) or not stages:
        problems.append("the timed stage list is %r" % (stages,))

    bound = layout.get("bound_constants") or {}
    for key in ("t_f1", "t_loc", "f1_chance", "loc_chance", "neutral_band", "sibling_gap_cap",
                "long_solution_floor", "correct_answer_bad_step_floor", "sub_gate_ceiling",
                "gate_value", "log_rate_tolerance", "log_elapsed_tolerance_fraction"):
        value = bound.get(key)
        if not isinstance(value, float) or not 0.0 < value < 1.0:
            problems.append("bound constant %s is %r, which is not a fraction in (0,1)"
                            % (key, value))
    # The two sub-gate denominators. A chance level at or above its gate would divide by zero or
    # by a negative number and turn the conjunctive ramp into a silent sign error.
    if isinstance(bound.get("t_f1"), float) and isinstance(bound.get("f1_chance"), float):
        if bound["t_f1"] <= bound["f1_chance"]:
            problems.append("t_f1 %r is not above f1_chance %r, so the sub-gate ramp has no span"
                            % (bound["t_f1"], bound["f1_chance"]))
    if isinstance(bound.get("t_loc"), float) and isinstance(bound.get("loc_chance"), float):
        if bound["t_loc"] <= bound["loc_chance"]:
            problems.append("t_loc %r is not above loc_chance %r, so the sub-gate ramp has no span"
                            % (bound["t_loc"], bound["loc_chance"]))
    # The sub-gate ceiling must sit strictly UNDER the gate value, or clearing both quality gates
    # could pay less than missing them.
    if isinstance(bound.get("sub_gate_ceiling"), float) and isinstance(bound.get("gate_value"),
                                                                      float):
        if bound["sub_gate_ceiling"] >= bound["gate_value"]:
            problems.append("sub_gate_ceiling %r is not below gate_value %r"
                            % (bound["sub_gate_ceiling"], bound["gate_value"]))
    for key in ("long_solution_min_steps", "long_solution_min_first_error_index"):
        if not isinstance(bound.get(key), int) or bound[key] < 0:
            problems.append("bound constant %s is %r, which is not a step count" % (key, bound.get(key)))
    if (isinstance(bound.get("long_solution_min_steps"), int)
            and isinstance(bound.get("long_solution_min_first_error_index"), int)
            and bound["long_solution_min_first_error_index"] >= bound["long_solution_min_steps"]):
        problems.append("the long-solution subgroup requires a first error at index %r inside a "
                        "solution of only %r steps, which no solution can satisfy"
                        % (bound["long_solution_min_first_error_index"],
                           bound["long_solution_min_steps"]))
    for key in ("graded_manifest", "graded_labels", "sibling_manifest", "sibling_labels"):
        if not str(layout.get(key, "")).startswith("tests/heldout/"):
            problems.append("corpus_layout %s is %r; the private shards live under tests/heldout/"
                            % (key, layout.get(key)))
    return problems


def main():
    g = load_grounding()
    # The validator runs FIRST and refuses rather than emitting.
    problems = validate(g)
    if problems:
        raise SystemExit("AELLO-C6-S2 grounding is not well-formed: " + "; ".join(problems))

    layout = g["corpus_layout"]
    bound = layout["bound_constants"]
    outcome_id = [i["id"] for i in g["items"] if i["dimension"] == "outcome"][0]
    subst = {
        "slot_id": SLOT_ID,
        "path": g["deliverable"]["path"],
        "outcome_id": outcome_id,
        "labels": tuple(layout["label_vocabulary"]),
        "sentinel": layout["no_error_sentinel"],
        "labels_key": "labels",
        "index_key": "first_error_index",
        "positional_keys": ("order", "position", "presentation_index", "rank", "row", "row_index"),
        "graded_manifest": os.path.basename(layout["graded_manifest"]),
        "graded_labels": os.path.basename(layout["graded_labels"]),
        "sibling_manifest": os.path.basename(layout["sibling_manifest"]),
        "sibling_labels": os.path.basename(layout["sibling_labels"]),
        "strata": tuple(layout["strata"]),
        "run_record": layout["run_record"],
        "reward_log": layout["reward_log"],
        "timed_stages": tuple(layout["timed_stages"]),
        "guarded": tuple(layout["guarded_prefixes"]),
        "t_f1": bound["t_f1"],
        "t_loc": bound["t_loc"],
        "f1_chance": bound["f1_chance"],
        "loc_chance": bound["loc_chance"],
        "neutral_band": bound["neutral_band"],
        "sibling_gap_cap": bound["sibling_gap_cap"],
        "long_min_steps": bound["long_solution_min_steps"],
        "long_min_index": bound["long_solution_min_first_error_index"],
        "long_floor": bound["long_solution_floor"],
        "answer_floor": bound["correct_answer_bad_step_floor"],
        "sub_gate_ceiling": bound["sub_gate_ceiling"],
        "gate_value": bound["gate_value"],
        "log_rate_tolerance": bound["log_rate_tolerance"],
        "log_elapsed_tolerance": bound["log_elapsed_tolerance_fraction"],
    }

    # EVERY compiled item carries a written body. The generic obligation lookup that used to stand
    # here is gone: it read a run-record key nothing writes, so any item falling through to it
    # graded nothing at all and said so in no report. Refuse instead of falling through.
    bodies = dict(BODIES)
    for it in g["items"]:
        if it["mode"] == "compiled" and it["id"] not in bodies:
            raise SystemExit("AELLO-C6-S2: no body written for compiled item %r; the generator "
                             "refuses rather than emitting a check that consults nothing"
                             % it["id"])
    orphans = sorted(set(bodies) - set(i["id"] for i in g["items"]))
    if orphans:
        raise SystemExit("AELLO-C6-S2: bodies written for items the grounding does not carry: %s"
                         % orphans)

    # The outcome check must SAY the slot is unmeasurable before it reads anything at all. If it
    # reads first, an absent artifact reports as an ordinary failure and the verifier then says
    # gradeable=true with r_det=0.0, collapsing two different claims into one.
    statements = [ln.strip() for ln in bodies[outcome_id].splitlines()
                  if ln.strip() and not ln.strip().startswith("#")]
    if not statements or statements[0] != REQUIRE_FIRST:
        raise SystemExit("AELLO-C6-S2: %r must call require_measured as its first statement, "
                         "before it reads any submitted byte" % outcome_id)

    tests_dir = os.path.join(BUNDLE, "tests")
    os.makedirs(tests_dir, exist_ok=True)

    # solution/TRUTH.md and solution/rubrics.json are PRIVATE_CARRIERS: seed/identity.py plants a
    # canary block into them at freeze, and canary normalisation is what keeps planting from
    # moving identity. A generator that rewrote them plainly would DROP the planted tripwire, and
    # the next content_hash would differ from the frozen one. So the planted block is carried
    # across the regeneration rather than recreated.
    truth_path = os.path.join(HERE, "TRUTH.md")
    truth = build_truth(g, TITLE).rstrip("\n") + "\n"
    keep = None
    if os.path.exists(truth_path):
        import re as _re
        m = _re.search(r"<!-- AELLO-CANARY-BLOCK.*?-->\n?", open(truth_path).read(), _re.S)
        keep = m.group(0) if m else None
    with open(truth_path, "w") as fh:
        fh.write(truth + ("\n" + keep if keep else ""))

    rub_path = os.path.join(HERE, "rubrics.json")
    rub = build_rubrics(g, ITEM_KEYS)
    if os.path.exists(rub_path):
        try:
            prev = json.load(open(rub_path))
            if "canary" in prev:
                rub["canary"] = prev["canary"]
        except Exception:
            pass
    with open(rub_path, "w") as fh:
        json.dump(rub, fh, indent=1, sort_keys=True)
        fh.write("\n")
    with open(os.path.join(tests_dir, "rubrics.json"), "w") as fh:
        json.dump(build_rubrics(g, ITEM_KEYS), fh, indent=1, sort_keys=True)
        fh.write("\n")
    with open(os.path.join(tests_dir, "test_output.py"), "w") as fh:
        # The tail arrives FINAL and UNSUBSTITUTED. It carries percent formatting of its own
        # inside the emitted helpers, so formatting it a second time raises TypeError.
        fh.write(build_tests(g, PRELUDE % subst, bodies) + TAIL)
    with open(os.path.join(tests_dir, "constants.json"), "w") as fh:
        json.dump(g["constants"], fh, indent=1, sort_keys=True)
        fh.write("\n")
    # ORDER MATTERS. `with open(path, "w")` truncates BEFORE its body's arguments are evaluated,
    # so calling read_identity() inside the with-statement reads the file this line just emptied
    # and writes nulls over the frozen identity. Read first, then open.
    prov = build_provenance(g, read_identity(HERE))
    with open(os.path.join(HERE, "provenance.yaml"), "w") as fh:
        # MATCH seed/build/screen_bind.py and the frozen generators exactly: sort_keys=True,
        # default_flow_style=False, width=100. The screen writes this carrier after the freeze,
        # so a generator using a different dump convention reorders the keys on the next
        # regeneration and reports as drift even though no value changed.
        yaml.safe_dump(prov, fh, sort_keys=True, default_flow_style=False, width=100,
                       allow_unicode=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

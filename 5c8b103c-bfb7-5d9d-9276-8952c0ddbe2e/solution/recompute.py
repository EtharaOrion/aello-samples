def carries_value(node, wanted, depth=0):
    """Whether a decoded payload holds `wanted` anywhere inside it.

    A file digest catches only a byte-identical copy. The private state of this slot can be held
    at three coarser granularities -- the first-error index vector, the per-id step-count map and
    the per-id stratum map -- and each of those can be re-serialised into a payload of the agent's
    own shape, so the search is by VALUE and not by digest.
    """
    if depth > 6:
        return False
    if node == wanted:
        return True
    if isinstance(node, dict):
        return any(carries_value(value, wanted, depth + 1) for value in node.values())
    if isinstance(node, list):
        return any(carries_value(value, wanted, depth + 1) for value in node)
    return False


def decoded_payloads(text):
    """Every JSON payload in a text file: the whole document, or one per JSONL line."""
    out = []
    try:
        out.append(json.loads(text))
    except ValueError:
        for line in text.splitlines():
            line = line.strip()
            if not line:
                continue
            try:
                out.append(json.loads(line))
            except ValueError:
                continue
    return out



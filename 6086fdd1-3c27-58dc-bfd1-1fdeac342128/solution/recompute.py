def roster_literal(words):
    """A deterministic Python literal for the pinned keyword roster, five words to a line.

    Written out of the grounding's own order rather than sorted here: the ORDER is the fact being
    pinned, and re-sorting it in the generator would quietly repair exactly the drift the check
    that reads it exists to catch.
    """
    rows = [words[i:i + 5] for i in range(0, len(words), 5)]
    return "(\n" + "".join("    " + " ".join("%r," % (w,) for w in row) + "\n"
                           for row in rows) + ")"


def validate(grounding):
    """Refuse a grounding this generator cannot honestly compile.

    Two families of problem are checked. The first is structural and applies to any slot: a closed
    item schema, one outcome item, an evaluation-target vocabulary with nothing unused in it, and
    ramp constants left null. The second is this slot's own arithmetic -- a 35-word roster in
    lexicographic order, a graded count that is the balanced product of the two counts that make
    it, a latency bound that is a positive number of milliseconds read as a maximum, a front-end
    envelope whose ranges are ordered and fit inside a one-second utterance, and a share cap that
    sits strictly between the balanced share and the whole vector. Each is checked here because a
    check emitted against a bound that contradicts the corpus is worse than no check at all.
    """
    problems = []
    items = grounding["items"]
    ids = [i["id"] for i in items]
    if len(set(ids)) != len(ids):
        problems.append("duplicate item ids: %r" % sorted(set(x for x in ids if ids.count(x) > 1)))
    for item in items:
        if frozenset(item) != ITEM_SCHEMA:
            problems.append("item %r does not carry the closed item schema" % item.get("id"))
            continue
        if item["outcome_class"] not in OUTCOME_CLASSES:
            problems.append("item %r has outcome_class %r" % (item["id"], item["outcome_class"]))
        if item["evaluation_target"] not in grounding["evaluation_target_vocabulary"]:
            problems.append("item %r evaluates %r, which the vocabulary does not admit"
                            % (item["id"], item["evaluation_target"]))
        if not isinstance(item["weight"], int) or item["weight"] <= 0:
            problems.append("item %r carries weight %r" % (item["id"], item["weight"]))
    targets = {i["evaluation_target"] for i in items}
    if "run_record" not in targets:
        problems.append("a gated slot must grade against the harness run record")
    unused = sorted(set(grounding["evaluation_target_vocabulary"]) - targets)
    if unused:
        problems.append("the vocabulary admits %s, which no item evaluates" % unused)
    outcome = [i["id"] for i in items if i["dimension"] == "outcome"]
    if len(outcome) != 1:
        problems.append("expected exactly one outcome item, found %r" % outcome)
    for name in RAMP:
        if grounding["constants"].get(name) is not None:
            problems.append("constant %r is authored at Phase 0; it is measured, not authored"
                            % name)

    layout = grounding.get("corpus_layout") or {}
    roster = list(layout.get("keyword_roster") or [])
    if len(roster) != layout.get("keyword_count") or len(set(roster)) != len(roster):
        problems.append("the keyword roster carries %d entries against a declared count of %r"
                        % (len(roster), layout.get("keyword_count")))
    if roster != sorted(roster):
        problems.append("the keyword roster is not in the lexicographic order it claims to pin")
    if any(word != word.strip().lower() for word in roster):
        problems.append("a keyword is not the lowercase folder name the corpus ships")
    per_keyword = layout.get("utterances_per_keyword")
    if not isinstance(per_keyword, int) or per_keyword <= 0:
        problems.append("utterances_per_keyword is %r; a balanced split needs a positive count"
                        % per_keyword)
    elif per_keyword * len(roster) != layout.get("graded_utterance_count"):
        problems.append("the graded count %r is not %d keywords times %d utterances"
                        % (layout.get("graded_utterance_count"), len(roster), per_keyword))
    if layout.get("class_balance_ratio") != 1.0:
        problems.append("the split is declared at ratio %r; this slot's metric is plain accuracy "
                        "and needs the 1.00:1 balance it publishes"
                        % layout.get("class_balance_ratio"))

    bound = layout.get("per_utterance_latency_bound_ms")
    if not isinstance(bound, float) or bound <= 0:
        problems.append("the per-utterance latency bound is %r; a gate needs a positive number of "
                        "milliseconds" % bound)
    if layout.get("latency_gate_statistic") != "maximum":
        problems.append("the gate statistic is %r; this slot's instruction says every inference, "
                        "and only a maximum says that" % layout.get("latency_gate_statistic"))
    overlap = sorted(set(layout.get("admitted_latency_sources") or [])
                     & set(layout.get("rejected_latency_sources") or []))
    if overlap:
        problems.append("latency source %s is both admitted and rejected" % overlap)
    if not layout.get("admitted_latency_sources"):
        problems.append("no admitted latency source; the gate would have nothing to read")
    if not layout.get("agent_timing_fields_refused"):
        problems.append("red line 2 needs the agent-timed fields it refuses named")

    rate = layout.get("sample_rate_hz")
    samples = layout.get("utterance_samples")
    if rate != samples:
        problems.append("a one-second utterance at %r Hz is %r samples, not %r"
                        % (rate, rate, samples))
    envelope = layout.get("front_end_envelope") or {}
    for field in FRONT_END_RANGES:
        span = envelope.get(field)
        if not (isinstance(span, list) and len(span) == 2
                and all(isinstance(v, int) for v in span) and 0 < span[0] <= span[1]):
            problems.append("front-end range %s is %r; it must be an ordered pair of positive "
                            "integers" % (field, span))
    window = envelope.get("window_samples")
    if isinstance(window, list) and len(window) == 2 and isinstance(samples, int):
        if window[1] > samples:
            problems.append("the widest declarable window %r does not fit inside a %r-sample "
                            "utterance" % (window[1], samples))
    for key in ("sample_rate_hz", "window_samples", "hop_samples", "mel_bands",
                "frames_per_utterance"):
        if key not in (layout.get("front_end_keys") or []):
            problems.append("front_end_keys does not name %r, which the frame arithmetic reads"
                            % key)

    cap = layout.get("max_single_keyword_share")
    if not isinstance(cap, float) or not (1.0 / max(len(roster), 1)) < cap < 1.0:
        problems.append("the share cap is %r; it must sit strictly between the balanced share and "
                        "the whole vector" % cap)
    clips = set(layout.get("background_noise_clips") or [])
    if clips != VENDORED_NOISE_CLIPS:
        problems.append("the background roster %s is not the six clips the release ships"
                        % sorted(clips))
    snr = layout.get("noise_snr_db_range")
    if not (isinstance(snr, list) and len(snr) == 2 and snr[0] < snr[1]):
        problems.append("the mixing range is %r; it must be an ordered pair of decibels" % snr)
    if not layout.get("budget_keys"):
        problems.append("no budget keys; the declaration check would grade an empty roster")
    guarded = layout.get("guarded_writes") or []
    if "tests/" not in guarded or layout.get("graded_audio") not in guarded:
        problems.append("the guarded roots %s do not cover the checker tree and the graded audio"
                        % guarded)
    return problems



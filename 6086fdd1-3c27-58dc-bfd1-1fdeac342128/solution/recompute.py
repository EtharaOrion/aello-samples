TAIL = r'''

# ------------------------------------------------------------------------------------------
# Reading the delivered bytes: one label vector, one run record, and the two corpus archives the
# verifier mounts. An absence is reported under its own reason and never guessed at, and no read
# here is allowed to take the verifier down -- a submission that will not open is a finding about
# the submission, not a traceback in the checker.
# ------------------------------------------------------------------------------------------

def load_submission():
    """The keyword decision vector: one integer per graded utterance."""
    import numpy as np
    array = np.load(SUBMISSION, allow_pickle=False)
    if array.dtype == object:
        raise ValueError("an object array is not a keyword decision vector")
    return array


def describe(array):
    return "%s%s" % (array.dtype, array.shape)


def integral(array):
    """True when the dtype itself is integral. A float vector of whole numbers is not.

    The deliverable is a decision, and a decision has no fractional part. Accepting float64
    because its entries happen to be whole would also accept a posterior row that was rounded on
    its way out, which is a different object with a different failure mode.
    """
    return array.dtype.kind in ("i", "u")


def label_rows(array):
    """The decisions as a flat list of Python ints, whatever shape or dtype they arrived in."""
    return [int(value) for value in array.ravel().tolist()]


def keyword_name(index):
    """The word a class index means, or a legible placeholder when it means none of them."""
    if 0 <= index < len(KEYWORD_ROSTER):
        return KEYWORD_ROSTER[index]
    return "index_" + str(index)


def keyword_histogram(array):
    """class index -> how many graded utterances were decided that way."""
    counts = {}
    for value in label_rows(array):
        counts[value] = counts.get(value, 0) + 1
    return counts


def graded_utterance_ids():
    """The graded roster in its pinned order, or None when the archive has not landed.

    None is not an empty roster. Every caller distinguishes the two: a check that cannot find the
    roster falls back to the pinned COUNT and says in its evidence which source it used, rather
    than passing because it had nothing to compare against.
    """
    if not os.path.exists(GRADED_AUDIO):
        return None
    try:
        import numpy as np
        archive = np.load(GRADED_AUDIO, allow_pickle=False)
        if "utterance_id" not in archive.files:
            return None
        return [str(u) for u in archive["utterance_id"].tolist()]
    except Exception:
        return None


def graded_truth():
    """(utterance ids, keyword indices) from the private labels, or None when they are absent."""
    if not os.path.exists(GRADED_LABELS):
        return None
    try:
        import numpy as np
        archive = np.load(GRADED_LABELS, allow_pickle=False)
        return ([str(u) for u in archive["utterance_id"].tolist()],
                [int(v) for v in archive["y"].tolist()])
    except Exception:
        return None


def run_record():
    """What the graded run and the harness recorded about the run.

    The agent writes most of this file, so it can be absent, truncated, or not JSON at all. Every
    one of those is an empty record here, and each check then reports its own missing-declaration
    reason instead of raising.
    """
    if not os.path.exists(RUN_RECORD):
        return {}
    try:
        with open(RUN_RECORD) as handle:
            doc = json.load(handle)
    except Exception:
        return {}
    return doc if isinstance(doc, dict) else {}


def numeric(value):
    """A finite float, or None for anything that is not one -- including bools and NaN.

    A bool is an int in Python, and True would otherwise read as a latency of one millisecond.
    """
    if isinstance(value, bool) or value is None:
        return None
    try:
        out = float(value)
    except (TypeError, ValueError):
        return None
    if out != out or out in (float("inf"), float("-inf")):
        return None
    return out


def token(value):
    """A declared vocabulary word, normalised the one way every roster here is written."""
    return str(value).strip().lower().replace("-", "_").replace(" ", "_")


def digest_field(record, key):
    """A recorded digest, lowercased and stripped, or the empty string when it is absent."""
    return str(record.get(key) or "").strip().lower()


# ------------------------------------------------------------------------------------------
# The latency side. Every millisecond a check reads comes from the harness's own series; nothing
# below consults a duration the graded process reported about itself.
# ------------------------------------------------------------------------------------------

def harness_latencies():
    """utterance id -> the HARNESS's measured wall clock for that one inference, as recorded.

    Red line 2 is measuring latency with a clock the agent controls, so the graded quantity is
    read from the harness's record and an agent-supplied series is never substituted for it.
    """
    got = run_record().get("harness_utterance_latency_ms")
    if not isinstance(got, dict):
        return {}
    return dict((str(k), v) for k, v in got.items())


def readable_latencies():
    """The harness series with every unreadable entry dropped, so a caller can count both."""
    out = {}
    for utterance, value in harness_latencies().items():
        milliseconds = numeric(value)
        if milliseconds is not None:
            out[utterance] = milliseconds
    return out


def gate_statistics():
    """(worst, mean, utterances over the bound) recomputed from the harness series.

    The maximum and the mean are computed side by side on purpose. The gate is the maximum; the
    mean is carried so the check that reads this can name the substitution when a run's own
    verdict agrees with the mean and disagrees with the maximum.
    """
    series = readable_latencies()
    if not series:
        return None, None, []
    values = list(series.values())
    over = sorted(u for u, ms in series.items() if ms > LATENCY_BOUND_MS)
    return max(values), sum(values) / float(len(values)), over


# ------------------------------------------------------------------------------------------
# The declaration side: the front end, its digest, and where a write landed.
# ------------------------------------------------------------------------------------------

def front_end_block():
    """The declared front-end configuration, or {} when the run declared none."""
    block = run_record().get("front_end")
    return block if isinstance(block, dict) and block else {}


def front_end_digest(block):
    """sha256 over the canonical form of a front-end block.

    Recomputed here rather than taken from the record, because the whole point of the two
    recorded digests is that they can be checked against the configuration they claim to cover.
    """
    canonical = json.dumps(dict((str(k), block[k]) for k in sorted(block)),
                           sort_keys=True, separators=(",", ":"))
    return hashlib.sha256(canonical.encode("utf-8")).hexdigest()


def recomputed_frames(window, hop):
    """Frames a one-second utterance yields at this window and hop, or None when it yields none."""
    if window < 1 or hop < 1 or window > UTTERANCE_SAMPLES:
        return None
    return 1 + (UTTERANCE_SAMPLES - window) // hop


def positive_frequency_bins(window):
    """The bin count a real FFT of this window returns, which caps the mel filterbank."""
    return window // 2 + 1


def guarded_root(path):
    """The guarded root a written path lands in, or None when it lands outside all of them."""
    flat = "/" + str(path).replace("\\", "/").lstrip("./").lstrip("/")
    for root in GUARDED_WRITES:
        needle = root if root.startswith("/") else "/" + root
        if needle in flat:
            return root
    return None


def artifact_digest():
    """sha256 of the delivered label vector, or None when nothing was delivered."""
    if not os.path.exists(SUBMISSION):
        return None
    with open(SUBMISSION, "rb") as handle:
        return hashlib.sha256(handle.read()).hexdigest()


def measure():
    """Top-1 keyword accuracy over the private split, gated per utterance before it is counted.

    The gate is applied FIRST and it is absolute: one inference above the bound returns 0.0, not a
    proportional penalty and not the accuracy that inference helped earn. That ordering is the
    whole shape of this slot's reward -- accuracy bought by exceeding the per-utterance budget is
    worth nothing, because a keyword spotter that answers late has not answered.

    Three conditions raise ConstantUnmeasured rather than returning a number, and all three are
    statements about this bundle rather than about the agent: no harness timings, no landed
    labels, and a landed roster whose order disagrees with the labels. Returning 0.0 for any of
    them would report that the agent scored nothing when the truth is that nothing was measurable.
    """
    declared = harness_latencies()
    if not declared:
        raise ConstantUnmeasured("the harness recorded no per-utterance latency, so the gate this "
                                 "metric applies before it counts anything cannot be evaluated")
    series = readable_latencies()
    if len(series) != len(declared):
        raise ConstantUnmeasured("the harness latency series carries an entry that is not a "
                                 "finite number of milliseconds")
    if max(series.values()) > LATENCY_BOUND_MS:
        return 0.0
    truth = graded_truth()
    if truth is None:
        raise ConstantUnmeasured("the private keyword labels have not landed under tests/heldout")
    utterances, gold = truth
    roster = graded_utterance_ids()
    if roster is not None and roster != utterances:
        raise ConstantUnmeasured("the landed graded roster and the private labels disagree on "
                                 "utterance order; that is a corpus landing to repair, not a "
                                 "score to report")
    try:
        predicted = label_rows(load_submission())
    except Exception:
        return 0.0
    if len(predicted) != len(gold):
        return 0.0
    hits = 0
    for guess, answer in zip(predicted, gold):
        if guess == answer:
            hits += 1
    return hits / float(len(gold))
'''



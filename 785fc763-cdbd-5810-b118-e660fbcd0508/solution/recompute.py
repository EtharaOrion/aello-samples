def bundled(rel):
    """A bundle-relative corpus path, resolved from the checker tree."""
    return os.path.join(BUNDLE, *rel.split("/"))


def load_submission():
    """The submitted label vector, flattened, as plain integers.

    Strict at load, so every later check reads labels rather than re-deciding what a label is. A
    float array is NOT rounded into a label vector here: choosing a rounding rule for the agent
    would be scoring a submission the agent did not make.
    """
    import numpy as np
    arr = np.load(SUBMISSION, allow_pickle=False)
    if arr.dtype == object:
        raise ValueError("object arrays are not a valid deliverable")
    if arr.dtype.kind not in ("i", "u"):
        raise ValueError("dtype %s is not an integer label vector" % arr.dtype)
    flat = arr.ravel()
    if flat.size == 0:
        raise ValueError("the label vector is empty; no graded image can be scored from nothing")
    return flat


def describe(arr):
    return "%s%s" % (arr.dtype, arr.shape)


def npz_member(rel, key):
    """One named member of a bundled .npz, or None when the shard has not landed."""
    path = bundled(rel)
    if not os.path.exists(path):
        return None
    import numpy as np
    archive = np.load(path, allow_pickle=False)
    if key not in archive.files:
        return None
    return np.asarray(archive[key])



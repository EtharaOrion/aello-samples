def first_statement(body):
    """The first executable line of a generated check body, comments and blanks skipped."""
    for line in body.splitlines():
        stripped = line.strip()
        if stripped and not stripped.startswith("#"):
            return stripped
    return ""


def validate(grounding, bodies):
    """Refuse a grounding this generator cannot faithfully compile.

    Slot-specific, not a stub. The 100-class domain and the corpus paths are emitted into the
    check module as literals, so a domain that did not match the corpus, or a layout key the
    bodies read and the grounding does not carry, would silently produce a check that consults
    nothing. The outcome guard is the one seed/build/freeze_batch.py refuses on: an outcome body
    that reads a submission before calling require_measured lets a missing-file error mask the
    unmeasured signal, and the verifier then reports gradeable true with r_det 0.0.
    """
    problems = []
    domain = grounding.get("label_domain") or {}
    classes, superclasses = domain.get("classes"), domain.get("coarse_superclasses")
    if not isinstance(classes, int) or classes < 2:
        problems.append("label_domain.classes must be an integer above one; got %r" % (classes,))
    if not isinstance(superclasses, int) or superclasses < 1:
        problems.append("label_domain.coarse_superclasses must be a positive integer; got %r"
                        % (superclasses,))
    elif isinstance(classes, int) and superclasses > classes:
        problems.append("coarse_superclasses %d exceeds the %d fine classes it groups"
                        % (superclasses, classes))
    if isinstance(classes, int) and classes > 0 and domain.get("chance") not in (None, 1.0 / classes):
        problems.append("label_domain.chance %r does not equal one over %d classes"
                        % (domain.get("chance"), classes))
    layout = grounding.get("corpus_layout") or {}
    for key in ("noisy_train_labels", "graded_labels", "train_clean_agreement", "coarse_map",
                "run_record", "status"):
        if not layout.get(key):
            problems.append("corpus_layout.%s is missing; a compiled check reads it" % key)
    private = grounding.get("private_split") or {}
    if not private.get("roots_the_agent_may_not_read"):
        problems.append("private_split.roots_the_agent_may_not_read is empty; red line 1 would "
                        "compile to a check that forbids nothing")
    vocabulary = set(grounding.get("evaluation_target_vocabulary") or ())
    seen = set()
    outcome = [i for i in grounding["items"] if i["dimension"] == "outcome"]
    for item in grounding["items"]:
        if item["id"] in seen:
            problems.append("duplicate item id %r" % item["id"])
        seen.add(item["id"])
        if not item["id"].isidentifier():
            problems.append("item id %r is not a Python identifier and cannot name a test"
                            % item["id"])
        if item["evaluation_target"] not in vocabulary:
            problems.append("item %s targets %r, which is outside the declared vocabulary"
                            % (item["id"], item["evaluation_target"]))
        if not isinstance(item["weight"], int) or item["weight"] <= 0:
            problems.append("item %s carries a non-positive weight" % item["id"])
        if set(item) != set(ITEM_KEYS) | {"outcome_class"}:
            problems.append("item %s does not carry the closed item schema" % item["id"])
    if not grounding["items"]:
        problems.append("no items; identifier set equality against the tests would pass vacuously")
    if len(outcome) != 1:
        problems.append("expected exactly one outcome item; found %d" % len(outcome))
    else:
        oid = outcome[0]["id"]
        if not outcome[0]["knockout"]:
            problems.append("the outcome item %s must be a knockout" % oid)
        body = bodies.get(oid, "")
        if not first_statement(body).startswith("c = require_measured("):
            problems.append("the outcome item %s must call require_measured as its FIRST "
                            "statement; seed/build/freeze_batch.py refuses a bundle that reads a "
                            "submission before it declares the slot unmeasurable" % oid)
    for name in ("floor", "knee", "dichotomizing_threshold", "reward_gate_pass_threshold"):
        if grounding["constants"].get(name) is not None:
            problems.append("constants.%s is authored; Phase 0 measures nothing" % name)
    return problems


def main():
    g = load_grounding()
    # EVERY compiled item is written by hand. No fallback: an item that reached a generic
    # obligations lookup would emit a check that consults a run-record key nobody writes, which
    # is a check that cannot fire dressed as a check that passed.
    bodies = dict(BODIES)
    orphan = [i["id"] for i in g["items"] if i["mode"] == "compiled" and i["id"] not in bodies]
    if orphan:
        raise SystemExit("AELLO-C8-S12: no body written for compiled item(s) %s. Write the check "
                         "or drop the item; there is no generic fallback." % ", ".join(orphan))
    unused = sorted(set(bodies) - {i["id"] for i in g["items"]})
    if unused:
        raise SystemExit("AELLO-C8-S12: body written for %s, which names no item"
                         % ", ".join(unused))
    # The validator runs BEFORE anything is emitted: a generator that writes a carrier it knows is
    # malformed hands the drift check a moving target.
    problems = validate(g, bodies)
    if problems:
        raise SystemExit("AELLO-C8-S12 grounding is not well-formed: " + "; ".join(problems))

    dl = g["deliverable"]
    domain = g["label_domain"]
    layout = g["corpus_layout"]
    subst = {"slot_id": SLOT_ID, "path": dl["path"],
             "classes": domain["classes"], "superclasses": domain["coarse_superclasses"],
             "noisy_labels": layout["noisy_train_labels"],
             "graded_labels": layout["graded_labels"],
             "train_agreement": layout["train_clean_agreement"],
             "coarse_map": layout["coarse_map"],
             "run_record": layout["run_record"],
             "private_roots": tuple(g["private_split"]["roots_the_agent_may_not_read"]),
             "guarded": ("tests/", "environment/data/clean_labels/", "/logs/verifier/")}

    tests_dir = os.path.join(BUNDLE, "tests")
    os.makedirs(tests_dir, exist_ok=True)

    # solution/TRUTH.md and solution/rubrics.json are PRIVATE_CARRIERS: seed/identity.py plants a
    # canary block into them at freeze, and canary normalisation is what keeps planting from
    # moving identity. A generator that rewrote them plainly would DROP the planted tripwire, and
    # the next content_hash would differ from the frozen one. So the planted block is carried
    # across the regeneration rather than recreated.
    truth_path = os.path.join(HERE, "TRUTH.md")
    truth = build_truth(g, TITLE).rstrip("\n") + "\n"
    keep = None
    if os.path.exists(truth_path):
        import re as _re
        m = _re.search(r"<!-- AELLO-CANARY-BLOCK.*?-->\n?", open(truth_path).read(), _re.S)
        keep = m.group(0) if m else None
    with open(truth_path, "w") as fh:
        fh.write(truth + ("\n" + keep if keep else ""))

    rub_path = os.path.join(HERE, "rubrics.json")
    rub = build_rubrics(g, ITEM_KEYS)
    if os.path.exists(rub_path):
        try:
            prev = json.load(open(rub_path))
            if "canary" in prev:
                rub["canary"] = prev["canary"]
        except Exception:
            pass
    with open(rub_path, "w") as fh:
        json.dump(rub, fh, indent=1, sort_keys=True)
        fh.write("\n")
    with open(os.path.join(tests_dir, "rubrics.json"), "w") as fh:
        json.dump(build_rubrics(g, ITEM_KEYS), fh, indent=1, sort_keys=True)
        fh.write("\n")
    with open(os.path.join(tests_dir, "test_output.py"), "w") as fh:
        # Only the PRELUDE is substituted. BODIES and TAIL are already resolved and legitimately
        # carry percent signs of their own inside the emitted helpers, and formatting them a
        # second time raised TypeError on the first slot that carried one.
        fh.write(build_tests(g, PRELUDE % subst, bodies) + TAIL)
    with open(os.path.join(tests_dir, "constants.json"), "w") as fh:
        json.dump(g["constants"], fh, indent=1, sort_keys=True)
        fh.write("\n")
    # ORDER MATTERS. `with open(path, "w")` truncates BEFORE its body's arguments are evaluated,
    # so calling read_identity() inside the with-statement reads the file this line just emptied
    # and writes nulls over the frozen identity. Read first, then open.
    prov = build_provenance(g, read_identity(HERE))
    with open(os.path.join(HERE, "provenance.yaml"), "w") as fh:
        # MATCH seed/build/screen_bind.py and the frozen generators exactly: sort_keys=True,
        # default_flow_style=False, width=100. The screen writes this carrier after the freeze,
        # so a generator using a different dump convention reorders the keys on the next
        # regeneration and reports as drift even though no value changed.
        yaml.safe_dump(prov, fh, sort_keys=True, default_flow_style=False, width=100,
                       allow_unicode=True)
    return 0



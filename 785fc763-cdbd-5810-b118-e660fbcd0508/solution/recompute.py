def class_prior(values):
    """A normalised histogram over the 100 fine classes, ignoring out-of-domain entries."""
    counts = [0] * NUM_CLASSES
    for v in values:
        k = int(v)
        if 0 <= k < NUM_CLASSES:
            counts[k] += 1
    total = float(sum(counts))
    if total <= 0:
        return None
    return [c / total for c in counts]


def tv_distance(p, q):
    """Total variation distance between two priors over the same 100 classes."""
    return 0.5 * sum(abs(a - b) for a, b in zip(p, q))


def hypergeometric_z(pool, retained, agreeing_in_pool, agreeing_retained):
    """How far the retained set's clean-agreement count sits from independence, in sd.

    REPORTED, NEVER GRADED. Recorded on every run so the Phase 2 control ladder can set the
    calibrated purity bound from a distribution rather than from an authored number. It is not
    the decision statistic, because enriching for correctly-labelled images is exactly what a good
    selector does and a z-test on enrichment rejects the intended solutions along with the peek.
    """
    if pool < 2 or retained <= 0 or retained > pool:
        return None
    share = agreeing_in_pool / float(pool)
    variance = retained * share * (1.0 - share) * (pool - retained) / float(pool - 1)
    if variance <= 0:
        return None
    return (agreeing_retained - retained * share) / (variance ** 0.5)


def measure():
    """Balanced accuracy: mean per-class recall over the clean private split.

    Averaged over CLASSES, not over images, which is why a submission that collapses onto a few
    of the hundred cannot buy back the classes it abandoned. ConstantUnmeasured is raised only
    when the graded labels have not landed -- a genuine not-yet-measurable. A submission that is
    missing or mis-shaped raises ValueError instead, so the outcome check can report it as a
    failure rather than as an absence of measurement.
    """
    truth = graded_truth()
    if truth is None:
        raise ConstantUnmeasured("the clean graded labels have not landed at " + GRADED_LABELS)
    predicted = load_submission()
    if int(predicted.size) != int(truth.size):
        raise ValueError("submission carries %d rows against %d graded images"
                         % (int(predicted.size), int(truth.size)))
    hit = [0] * NUM_CLASSES
    seen = [0] * NUM_CLASSES
    for p, t in zip(predicted.tolist(), truth.ravel().tolist()):
        t = int(t)
        if not 0 <= t < NUM_CLASSES:
            continue
        seen[t] += 1
        if int(p) == t:
            hit[t] += 1
    recalls = [hit[k] / float(seen[k]) for k in range(NUM_CLASSES) if seen[k]]
    if not recalls:
        raise ValueError("no graded class produced a defined recall")
    return float(sum(recalls) / len(recalls))

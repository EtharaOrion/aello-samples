def in_guarded_tree(path):
    """True when a written path lands in the checker tree or on a graded tile archive."""
    flat = "/" + str(path).replace("\\\\", "/").lstrip("./").lstrip("/")
    return any(token in flat for token in GUARDED_WRITES)


def archive_content_digest():
    """sha256 over member names, dtypes, shapes and raw bytes, in the archive's stored order.

    NOT the file digest. An npz is a zip and its member headers carry whatever timestamp
    convention the writing library uses, so hashing the file measures numpy's release as much
    as it measures the run. Stored order is inside this digest on purpose: member order IS a
    property of the run, and a solve that iterates a dictionary to write its tiles produces the
    same masks in a different archive.
    """
    import hashlib
    import numpy as np
    if not os.path.exists(SUBMISSION):
        return None
    digest = hashlib.sha256()
    with np.load(SUBMISSION, allow_pickle=False) as archive:
        for name in archive.files:
            member = np.ascontiguousarray(archive[name])
            digest.update(name.encode("utf-8"))
            digest.update(("%s%s" % (member.dtype.str, member.shape)).encode("utf-8"))
            digest.update(member.tobytes())
    return digest.hexdigest()


def aligned_prediction(submitted, tile, truth):
    """The submitted mask for one graded tile, or None when it is missing or off the grid.

    Off-grid is deliberately NOT resampled. A mask on another grid is not a weaker answer to
    this tile's question, it is an answer to a different one, and it scores as an empty
    prediction: full union, no intersection.
    """
    member = submitted.get(tile)
    if member is None:
        return None
    if tuple(getattr(member, "shape", ())) != tuple(truth.shape):
        return None
    return member


def measure():
    """Mean per-class IoU: pooled per land-cover class, absent classes dropped, not credited.

    Pooling is per class across the whole graded tile set, so a class that occurs in one tile
    out of a thousand still carries one full term of the mean. A class whose pooled union is
    empty contributes NO term: an empty intersection over an empty union is undefined, and
    scoring it 1.0 would pay for every class nobody predicted and no tile contained.
    """
    import numpy as np
    if not os.path.exists(GRADED_MASKS):
        raise ConstantUnmeasured(
            "the private graded mask archive is not mounted; mean per-class IoU is not "
            "measurable from these bytes and reporting a number would be inventing one")
    try:
        submitted = load_submission()
    except Exception:
        submitted = {}
    intersection, union = {}, {}
    with np.load(GRADED_MASKS, allow_pickle=False) as truth_archive:
        for tile in sorted(truth_archive.files):
            truth = np.asarray(truth_archive[tile])
            predicted = aligned_prediction(submitted, tile, truth)
            labels = set(int(v) for v in np.unique(truth))
            if predicted is not None:
                labels |= set(int(v) for v in np.unique(np.asarray(predicted)))
            for label in sorted(labels):
                hit = truth == label
                guess = (np.asarray(predicted) == label if predicted is not None
                         else np.zeros(truth.shape, dtype=bool))
                intersection[label] = intersection.get(label, 0) + int((hit & guess).sum())
                union[label] = union.get(label, 0) + int((hit | guess).sum())
    graded_classes = class_index() or sorted(union)
    per_class = [intersection.get(c, 0) / union[c] for c in graded_classes if union.get(c, 0)]
    if not per_class:
        raise ConstantUnmeasured("no land-cover class has a non-empty union over the graded tiles")
    return float(sum(per_class) / len(per_class))

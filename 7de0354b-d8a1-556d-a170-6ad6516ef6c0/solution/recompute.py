def band_scale(entry):
    """The scale a band declaration carries, whichever key it names it by."""
    if isinstance(entry, dict):
        for key in ("scale", "std", "stddev", "sigma"):
            if key in entry:
                return float(entry[key])
        raise KeyError("no scale key in band declaration")
    if isinstance(entry, (list, tuple)) and len(entry) == 2:
        return float(entry[1])
    return float(entry)



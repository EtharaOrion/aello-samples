def describe(obj):
    return ",".join("%s:%s" % (k, tuple(v.shape)) for k, v in sorted(obj.items())[:4])


def archive_shapes(path):
    """member -> shape for one of the shipped tile archives; empty when it will not read.

    Empty covers two cases and the checks distinguish them by what else is available: the
    archive has not landed in this tree, or it landed and no longer parses. The second is red
    line 1 happening in front of the verifier, so it must produce a report rather than an
    unhandled traceback -- an archive that will not open is a finding, not a crash.
    """
    import numpy as np
    if not os.path.exists(path):
        return {}
    try:
        with np.load(path, allow_pickle=False) as archive:
            return {name: tuple(archive[name].shape) for name in archive.files}
    except Exception:
        return {}



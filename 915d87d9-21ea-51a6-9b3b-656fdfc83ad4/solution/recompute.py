# Reading the harness run record. Every quantity a red line turns on is measured by the harness,
# so it is read from here rather than from anything the recipe reported about itself.
# ----------------------------------------------------------------------------------------------


def run_record():
    path = os.path.join(HERE, "..", RUN_RECORD)
    if not os.path.exists(path):
        return {}
    with open(path) as handle:
        return json.load(handle)


def as_float(value):
    try:
        return float(value)
    except (TypeError, ValueError):
        return None


def ratio_of(numerator, denominator):
    top, bottom = as_float(numerator), as_float(denominator)
    if top is None or bottom is None or bottom <= 0:
        return None
    return top / bottom


def throughput_trials(kind):
    table = run_record().get("throughput_trials")
    if not isinstance(table, dict):
        raise ValueError("the run record carries no decode trial table")
    side = table.get(kind)
    if not isinstance(side, dict):
        raise ValueError("the trial table has no %r side" % kind)
    return side


def trial_rates(kind, batch):
    try:
        rows = throughput_trials(kind).get(str(batch)) or []
    except ValueError:
        return []
    rates = []
    for row in rows:
        value = as_float(row.get("tokens_per_second")) if isinstance(row, dict) else None
        if value is not None:
            rates.append(value)
    return rates


def all_trials():
    """Every timed trial, with the side and batch size it belongs to attached."""
    rows = []
    for kind in ("export", "bf16_baseline"):
        try:
            side = throughput_trials(kind)
        except ValueError:
            continue
        for batch in BATCH_SIZES:
            for row in side.get(str(batch)) or []:
                if isinstance(row, dict):
                    entry = dict(row)
                    entry.setdefault("batch_size", batch)
                    entry["kind"] = kind
                    rows.append(entry)
    return rows


def median(values):
    ordered = sorted(values)
    count = len(ordered)
    if not count:
        raise ValueError("a median needs at least one trial")
    middle = count // 2
    return ordered[middle] if count % 2 else 0.5 * (ordered[middle - 1] + ordered[middle])


def interquartile_range(values):
    """Nearest-rank quartiles, so five trials give a q1 and a q3 that a trial actually produced
    rather than an interpolation between two of them."""
    ordered = sorted(values)
    count = len(ordered)
    if not count:
        raise ValueError("an interquartile range needs at least one trial")
    low = ordered[max(0, int(math.ceil(0.25 * count)) - 1)]
    high = ordered[max(0, int(math.ceil(0.75 * count)) - 1)]
    return high - low


def batch_medians(kind):
    """The median rate at each published batch size, or a refusal if a batch is short of trials."""
    out = {}
    for batch in BATCH_SIZES:
        rates = trial_rates(kind, batch)
        if len(rates) != TRIALS:
            raise ValueError("%s at batch %d carries %d trials, not %d"
                             % (kind, batch, len(rates), TRIALS))
        out[batch] = median(rates)
    return out


def geometric_mean(per_batch):
    """The geometric mean across batch sizes.

    This is the shape of the metric and not a stylistic choice about averaging. Doubling the rate
    at one batch size while halving it at the other leaves the geometric mean where it started,
    so a recipe that wins the launch-bound regime by giving up the memory-bound one gains nothing.
    """
    product = 1.0
    for batch in sorted(per_batch):
        rate = per_batch[batch]
        if rate <= 0:
            raise ValueError("the decode rate at batch %s is not positive" % batch)
        product *= rate
    return product ** (1.0 / len(per_batch)) if per_batch else 0.0


def normalized_speedup():
    """s = T / T0, both sides the same statistic under the same protocol in the same run."""
    export = geometric_mean(batch_medians("export"))
    baseline = geometric_mean(batch_medians("bf16_baseline"))
    if baseline <= 0:
        raise ValueError("the bf16 baseline throughput was not measured in this run")
    return export / baseline

# ----------------------------------------------------------------------------------------------
# Reading the export. The manifest is read as a claim and the shard bytes as the fact; the two
# are compared, and where they disagree the bytes win.
# ----------------------------------------------------------------------------------------------


def manifest():
    with open(MANIFEST) as handle:
        doc = json.load(handle)
    if not isinstance(doc, dict):
        raise ValueError("the export manifest must be an object")
    return doc


def layer_rows():
    rows = manifest().get("layers")
    if not isinstance(rows, list):
        raise ValueError("the manifest carries no per-layer format map")
    return [row for row in rows if isinstance(row, dict)]


def pinned_roster():
    """The linear projections of the pinned checkpoint, in block-then-projection order."""
    return ["model.layers.%d.%s" % (block, projection)
            for block in range(TRANSFORMER_BLOCKS) for projection in PROJECTIONS]


def price_of(fmt):
    """Bits per weight for one published format, priced from that format's own fields.

    Payload, plus the group's amortised scale and zero point. Nothing here is a measurement: the
    table is exact arithmetic over integers the runtime contract publishes, which is why the
    vendor notes' uniform INT4 group-128 recommendation can be refused without running anything.
    """
    spec = FORMAT_CONTRACT.get(fmt)
    if spec is None:
        return None
    group = int(spec["group_size"])
    if group <= 0:
        raise ValueError("format %r declares a non-positive group size" % fmt)
    amortised = float(spec["scale_bits"]) + float(spec["zero_point_bits"])
    return float(spec["payload_bits"]) + amortised / group


def shard_files():
    names = []
    for shard in manifest().get("shards") or []:
        name = shard.get("file") if isinstance(shard, dict) else shard
        names.append(os.path.join(SHARD_DIR, os.path.basename(str(name))))
    return names


def on_disk_packed_bytes():
    """The size of the export as the filesystem reports it.

    The manifest's own per-layer byte counts are read separately and compared against this. They
    are never substituted for it, because the padding-inflated packing route works precisely by
    declaring a byte count the packer did not write.
    """
    total = 0
    for path in shard_files():
        if not os.path.exists(path):
            raise ValueError("the manifest names a shard that is not on disk: %s" % path)
        total += os.path.getsize(path)
    if not total:
        raise ValueError("the export packs no bytes at all")
    return total


def total_weight_count(rows):
    total = 0
    for row in rows:
        try:
            total += int(row.get("weight_count", 0))
        except (TypeError, ValueError):
            continue
    return total


def format_map_digest():
    """SHA-256 over the per-layer format map in ROSTER order, not in listing order.

    The map is an ordered assignment of a format to each projection of the pinned checkpoint, so
    a manifest that shuffles its own rows is the same map and must digest the same. Re-execution
    is compared against this digest and never against the packed bytes.
    """
    rows = {str(row.get("name")): row for row in layer_rows()}
    lines = []
    for name in pinned_roster():
        row = rows.get(name) or {}
        lines.append("%s\\t%s\\t%s" % (name, row.get("format"), row.get("group_size")))
    return hashlib.sha256("\\n".join(lines).encode("utf-8")).hexdigest()



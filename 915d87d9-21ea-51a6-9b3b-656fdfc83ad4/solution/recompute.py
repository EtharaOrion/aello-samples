def render(template, bindings):
    """Substitute {{NAME}} placeholders. Deliberately not printf formatting: the emitted module
    is full of percent signs of its own and a second format pass over it raised TypeError on the
    first slot that carried one."""
    out = template
    for name, value in bindings.items():
        out = out.replace("{{%s}}" % name, value)
    left = [line for line in out.split("\n") if "{{" in line]
    if left:
        raise SystemExit("%s: unresolved placeholder in the emitted prelude: %r"
                         % (SLOT_ID, left[0].strip()[:70]))
    return out



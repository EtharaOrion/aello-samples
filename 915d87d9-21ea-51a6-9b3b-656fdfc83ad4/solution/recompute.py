def validate(grounding):
    """Refuse to emit from a derivation source this slot cannot honestly compile.

    Every rule below is a defect that has actually shipped somewhere in this batch:

      1. An item without a body used to fall through to a generic obligation lookup that read a
         run-record key nothing writes, so the check consulted nothing and reported a pass.
      2. The outcome item must call require_measured as its FIRST statement. Reading the run
         record first lets a missing-file error mask the unmeasured signal, and the verifier then
         reports gradeable=true with r_det=0.0, collapsing "not yet measurable" into "the agent
         scored zero".
      3. The four measured constants stay null at Phase 0. A generator that emitted an authored
         floor would be inventing the measurement the whole convention exists to withhold.
      4. The format cost table has to price the decoy over the budget and the cheapest uniform row
         under it. If that arithmetic ever stopped holding, the vendor-notes control would stop
         being a control and the slot would have no measured-wrong popular route at all.
      5. The layer roster has to multiply out. blocks x projections is the denominator of the
         average bits per weight, and a wrong denominator is a silently wrong budget check.
    """
    problems = []
    items = grounding.get("items") or []
    if not items:
        problems.append("no items to compile")

    seen = set()
    for item in items:
        iid = item.get("id", "<unnamed>")
        if iid in seen:
            problems.append("duplicate item id %r" % iid)
        seen.add(iid)
        if set(item) != ITEM_SCHEMA:
            problems.append("item %r does not carry the closed schema: %s"
                            % (iid, sorted(set(item) ^ ITEM_SCHEMA)))
            continue
        if item["outcome_class"] not in OUTCOME_CLASSES:
            problems.append("item %r carries outcome_class %r" % (iid, item["outcome_class"]))
        if item["evaluation_target"] not in grounding["evaluation_target_vocabulary"]:
            problems.append("item %r evaluates %r, which the vocabulary does not admit"
                            % (iid, item["evaluation_target"]))
        if not isinstance(item["weight"], int) or item["weight"] <= 0:
            problems.append("item %r carries weight %r" % (iid, item["weight"]))

    compiled = {i["id"] for i in items if i["mode"] == "compiled"}
    for iid in sorted(compiled - set(BODIES)):
        problems.append("compiled item %r carries no body; this generator refuses rather than "
                        "emitting a check that consults nothing" % iid)
    for iid in sorted(set(BODIES) - compiled):
        problems.append("body %r belongs to no compiled item" % iid)

    outcome = [i for i in items if i["dimension"] == OUTCOME_DIMENSION]
    if [i["id"] for i in outcome] != [OUTCOME_ITEM]:
        problems.append("expected exactly one %r item named %r, found %r"
                        % (OUTCOME_DIMENSION, OUTCOME_ITEM, [i["id"] for i in outcome]))
    elif OUTCOME_ITEM in BODIES:
        statements = [line.strip() for line in BODIES[OUTCOME_ITEM].split("\n")
                      if line.strip() and not line.strip().startswith("#")]
        head = statements[0] if statements else ""
        if head != REQUIRE_FIRST:
            problems.append("%s must call require_measured on floor, knee and "
                            "dichotomizing_threshold as its first statement, before it reads the "
                            "run record; its first statement is %r" % (OUTCOME_ITEM, head[:70]))

    for name in RAMP_CONSTANTS:
        if grounding["constants"].get(name) is not None:
            problems.append("measured constant %r was authored at Phase 0; it is measured on the "
                            "grading host, not written here" % name)

    bounds = grounding["published_bounds"]
    roster = bounds["transformer_blocks"] * len(bounds["projections_per_block"])
    if roster != bounds["linear_layer_count"]:
        problems.append("the layer roster does not multiply out: %d blocks x %d projections is "
                        "%d, not the declared %d"
                        % (bounds["transformer_blocks"], len(bounds["projections_per_block"]),
                           roster, bounds["linear_layer_count"]))

    hidden = int(bounds["hidden_size"])
    counts = bounds["weight_count_by_projection"]
    expected = {
        "self_attn.q_proj": hidden * hidden,
        "self_attn.o_proj": hidden * hidden,
        "self_attn.k_proj": hidden * int(bounds["key_value_heads"]) * int(bounds["head_dim"]),
        "self_attn.v_proj": hidden * int(bounds["key_value_heads"]) * int(bounds["head_dim"]),
        "mlp.gate_proj": hidden * int(bounds["intermediate_size"]),
        "mlp.up_proj": hidden * int(bounds["intermediate_size"]),
        "mlp.down_proj": hidden * int(bounds["intermediate_size"]),
    }
    if int(bounds["attention_heads"]) * int(bounds["head_dim"]) != hidden:
        problems.append("%d attention heads at head_dim %d do not span hidden_size %d"
                        % (bounds["attention_heads"], bounds["head_dim"], hidden))
    for projection, want in sorted(expected.items()):
        if counts.get(projection) != want:
            problems.append("projection %r is declared at %r weights, but the pinned shapes give "
                            "%d" % (projection, counts.get(projection), want))
    if sorted(counts) != sorted(bounds["projections_per_block"]):
        problems.append("the weight-count table and the projection roster name different layers")
    summed = sum(counts.values()) * int(bounds["transformer_blocks"])
    if summed != int(bounds["linear_weight_total"]):
        problems.append("the per-block weight counts sum to %d over %d blocks, not the declared "
                        "%d" % (summed, bounds["transformer_blocks"],
                                bounds["linear_weight_total"]))

    contract = grounding["runtime_format_contract"]
    priced = {}
    for row in contract["rows"]:
        group = int(row["group_size"])
        if group <= 0:
            problems.append("format %r declares a non-positive group size" % row["format"])
            continue
        priced[row["format"]] = (float(row["payload_bits"])
                                 + (float(row["scale_bits"])
                                    + float(row["zero_point_bits"])) / group)
    budget = float(bounds["bit_budget_bits_per_weight"])
    decoy = priced.get(contract["decoy_row"])
    cheapest = priced.get(contract["cheapest_uniform_row_that_fits"])
    if decoy is None or decoy <= budget:
        problems.append("the decoy row %r prices at %r, which does not exceed the %r budget it is "
                        "supposed to fail" % (contract["decoy_row"], decoy, budget))
    if cheapest is None or cheapest > budget:
        problems.append("the cheapest uniform row %r prices at %r, which does not fit the %r "
                        "budget" % (contract["cheapest_uniform_row_that_fits"], cheapest, budget))
    if contract["per_format_decode_throughput"] is not None:
        problems.append("per-format decode throughput was authored at Phase 0; it is measured on "
                        "the grading host with the runtime's own kernels")
    if priced.get(PASSTHROUGH_FORMAT) is None:
        problems.append("the format contract has no %r row, so a layer left unquantized could "
                        "not be declared at all" % PASSTHROUGH_FORMAT)

    shares = grounding["contract_recorded_projections"]["reference_allocation_weight_mass_shares"]
    if abs(sum(shares.values()) - 1.0) > 1e-9:
        problems.append("the reference allocation shares sum to %r, not to one"
                        % sum(shares.values()))
    reference = sum(priced.get(fmt, 0.0) * share for fmt, share in shares.items())
    if reference > budget:
        problems.append("the reference allocation prices at %r, above its own %r budget"
                        % (reference, budget))

    cited = set()
    for step in grounding["truth_narrative"]["steps"]:
        cited.update(step["satisfies"])
    stray = sorted(cited - {i["id"] for i in items})
    if stray:
        problems.append("the narrative cites checks that do not exist: %s" % stray)
    uncited = sorted({i["id"] for i in items} - cited)
    if uncited:
        problems.append("no narrative step reaches these checks: %s" % uncited)

    return problems


def main():
    grounding = load_grounding()
    # The validator runs FIRST and refuses rather than emitting: a generator that writes a carrier
    # it knows is malformed hands the drift check a moving target.
    problems = validate(grounding)
    if problems:
        raise SystemExit("%s grounding is not well-formed: %s" % (SLOT_ID, "; ".join(problems)))

    layout = grounding["corpus_layout"]
    bounds = grounding["published_bounds"]
    contract = grounding["runtime_format_contract"]
    formats = {row["format"]: {"payload_bits": row["payload_bits"],
                               "scale_bits": row["scale_bits"],
                               "zero_point_bits": row["zero_point_bits"],
                               "group_size": row["group_size"]}
               for row in contract["rows"]}

    prelude = render(PRELUDE, {
        "SLOT": SLOT_ID,
        "OUTCOME": OUTCOME_ITEM,
        "MANIFEST": repr(grounding["deliverable"]["path"]),
        "EXPORT_ROOT": repr(layout["export_root"]),
        "RECIPE": repr(layout["recipe_program"]),
        "SHARD_DIR": repr(layout["shard_dir"]),
        "RUN_RECORD": repr(layout["run_record"]),
        "PINNED_CHECKPOINT": repr(layout["pinned_checkpoint"]),
        "BLOCKS": repr(bounds["transformer_blocks"]),
        "PROJECTIONS": repr(tuple(bounds["projections_per_block"])),
        "LAYERS": repr(bounds["linear_layer_count"]),
        "WEIGHT_COUNTS": json.dumps(bounds["weight_count_by_projection"], indent=4,
                                    sort_keys=True),
        "WEIGHT_TOTAL": repr(int(bounds["linear_weight_total"])),
        "BIT_BUDGET": repr(float(bounds["bit_budget_bits_per_weight"])),
        "CALIB_S": repr(float(bounds["calibration_budget_seconds"])),
        "PPL_GATE": repr(float(bounds["perplexity_gate_ratio"])),
        "PPL_STARTER": repr(float(bounds["starter_perplexity_ratio"])),
        "SUB_GATE": repr(float(bounds["sub_gate_credit_ceiling"])),
        "GAP_BOUND": repr(float(bounds["retention_gap_bound"])),
        "REEXEC_TOL": repr(float(bounds["reexecution_perplexity_tolerance"])),
        "IQR_BAND": repr(float(bounds["trial_iqr_band"])),
        "MAX_REMEASURES": repr(int(bounds["max_remeasures"])),
        "WARMUP": repr(int(bounds["warmup_steps"])),
        "DECODE_STEPS": repr(int(bounds["measured_decode_steps"])),
        "TRIALS": repr(int(bounds["trials"])),
        "BATCH_SIZES": repr(tuple(bounds["batch_sizes"])),
        "STAGES": repr(tuple(bounds["recipe_stage_vocabulary"])),
        "FORMAT_CONTRACT": json.dumps(formats, indent=4, sort_keys=True),
        "PASSTHROUGH": repr(PASSTHROUGH_FORMAT),
        "DECOY": repr(contract["decoy_row"]),
        "CHEAPEST": repr(contract["cheapest_uniform_row_that_fits"]),
        "GUARDED": repr(tuple(layout["guarded_prefixes"])),
        "HELDOUT": repr(layout["heldout_prefix"]),
        # SORTED TUPLES, not repr(frozenset(...)). A frozenset's repr orders by hash, which moves
        # with PYTHONHASHSEED, so the generator emitted a different byte sequence on every run and
        # the freeze's "regeneration is not canary-preserving" refusal fired on a set literal.
        "ALLOWLIST": "frozenset(%r)" % (tuple(sorted(layout["declared_egress_allowlist"])),),
        "HUBS": "frozenset(%r)" % (tuple(sorted(layout["model_hub_hosts"])),),
    })

    tests_dir = os.path.join(BUNDLE, "tests")
    os.makedirs(tests_dir, exist_ok=True)

    # EVERYTHING IS COMPUTED BEFORE ANY OUTPUT FILE IS OPENED. `with open(path, "w")` truncates
    # before its body's arguments are evaluated, so a read inside the with-statement reads the
    # file that line just emptied. That shipped once here, over the frozen identity block.
    truth = build_truth(grounding, TITLE).rstrip("\n") + "\n"
    rubrics = build_rubrics(grounding, ITEM_KEYS)
    module = build_tests(grounding, prelude, BODIES) + TAIL
    provenance = build_provenance(grounding, read_identity(HERE))

    # solution/TRUTH.md and solution/rubrics.json are PRIVATE_CARRIERS: seed/identity.py plants a
    # canary block into them at freeze, and canary normalisation is what keeps planting from
    # moving identity. A generator that rewrote them plainly would DROP the planted tripwire, and
    # the next content hash would differ from the frozen one. So the planted block is carried
    # across the regeneration rather than recreated.
    truth_path = os.path.join(HERE, "TRUTH.md")
    planted = None
    if os.path.exists(truth_path):
        import re as _re
        found = _re.search(r"<!-- AELLO-CANARY-BLOCK.*?-->\n?", open(truth_path).read(), _re.S)
        planted = found.group(0) if found else None

    rubrics_path = os.path.join(HERE, "rubrics.json")
    if os.path.exists(rubrics_path):
        try:
            previous = json.load(open(rubrics_path))
            if "canary" in previous:
                rubrics["canary"] = previous["canary"]
        except Exception:
            pass

    with open(truth_path, "w") as handle:
        handle.write(truth + ("\n" + planted if planted else ""))
    with open(rubrics_path, "w") as handle:
        json.dump(rubrics, handle, indent=1, sort_keys=True)
        handle.write("\n")
    with open(os.path.join(tests_dir, "rubrics.json"), "w") as handle:
        json.dump(build_rubrics(grounding, ITEM_KEYS), handle, indent=1, sort_keys=True)
        handle.write("\n")
    with open(os.path.join(tests_dir, "test_output.py"), "w") as handle:
        handle.write(module)
    with open(os.path.join(tests_dir, "constants.json"), "w") as handle:
        json.dump(grounding["constants"], handle, indent=1, sort_keys=True)
        handle.write("\n")
    with open(os.path.join(HERE, "provenance.yaml"), "w") as handle:
        # MATCH seed/build/screen_bind.py and the frozen generators exactly: sort_keys=True,
        # default_flow_style=False, width=100. The screen writes this carrier after the freeze,
        # so a generator using a different dump convention reorders the keys on the next
        # regeneration and reports as drift even though no value changed.
        yaml.safe_dump(provenance, handle, sort_keys=True, default_flow_style=False, width=100,
                       allow_unicode=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

def validate(grounding):
    """Refuse on a malformed derivation source rather than emitting a checker from one.

    The family validator that stood here asserted one thing -- that a `deliverable_shape` item
    existed and was a knockout -- which was true of a bundle whose every other item graded
    nothing. These are the invariants the emitted checker actually depends on.
    """
    problems = []
    items = grounding.get("items") or []
    if not items:
        problems.append("no items to compile")
    seen = set()
    for item in items:
        iid = item.get("id", "<unnamed>")
        if iid in seen:
            problems.append("duplicate item id %r" % iid)
        seen.add(iid)
        if set(item) != ITEM_SCHEMA:
            problems.append("item %r does not carry the closed schema: %s"
                            % (iid, sorted(set(item) ^ ITEM_SCHEMA)))
            continue
        if item["outcome_class"] not in OUTCOME_CLASSES:
            problems.append("item %r has outcome_class %r" % (iid, item["outcome_class"]))
        if item["evaluation_target"] not in grounding["evaluation_target_vocabulary"]:
            problems.append("item %r evaluates %r, which the vocabulary does not admit"
                            % (iid, item["evaluation_target"]))
        if not isinstance(item["weight"], int) or item["weight"] <= 0:
            problems.append("item %r carries weight %r" % (iid, item["weight"]))

    outcome = [i["id"] for i in items if i.get("dimension") == "outcome"]
    if len(outcome) != 1:
        problems.append("expected exactly one outcome item, found %r" % outcome)

    for name in RAMP:
        if grounding["constants"].get(name) is not None:
            problems.append("constant %r is authored at Phase 0; it is measured, not authored"
                            % name)

    if grounding["deliverable"].get("kind") != "python_module":
        problems.append("the graded deliverable of this slot is a callable recipe module, not %r"
                        % grounding["deliverable"].get("kind"))

    layout = grounding.get("corpus_layout") or {}
    classes = layout.get("classes") or []
    if len(classes) != layout.get("class_count"):
        problems.append("the class roster holds %d labels and class_count says %r"
                        % (len(classes), layout.get("class_count")))
    if len(set(classes)) != len(classes):
        problems.append("the class roster repeats a label")

    known_ops = set((layout.get("op_names") or {}).values())
    stray = sorted({op for pair in (layout.get("required_op_precedences") or []) for op in pair}
                   - known_ops)
    if stray:
        problems.append("required_op_precedences names %s, which op_names does not" % stray)
    stray = sorted(set(layout.get("augmentation_ops") or []) - known_ops)
    if stray:
        problems.append("augmentation_ops names %s, which op_names does not" % stray)

    # The two site bounds are AUTHORED, not measured, so the one thing that can be checked here
    # is that they are fractions and that they are not silently a pass for everything.
    for key in ("site_coverage_floor", "max_single_site_share"):
        value = layout.get(key)
        if not isinstance(value, float) or not 0.0 < value <= 1.0:
            problems.append("corpus_layout %s is %r, which is not a fraction in (0,1]"
                            % (key, value))
    return problems



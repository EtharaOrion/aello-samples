def heldout(name):
    """A verifier-side table. Lives under tests/heldout/ and the graded run may not read it."""
    return os.path.join(HERE, "heldout", name)


def run_record():
    path = os.path.normpath(os.path.join(HERE, RUN_RECORD))
    if not os.path.exists(path):
        return {}
    try:
        with open(path) as handle:
            doc = json.load(handle)
    except Exception:
        return {}
    return doc if isinstance(doc, dict) else {}


def recipe_source():
    """The recipe as TEXT. It is never imported: importing it to inspect it would run it."""
    with open(SUBMISSION, encoding="utf-8", errors="replace") as handle:
        return handle.read()


def recipe_ast():
    """The parsed recipe. Raises SyntaxError, which every caller reports rather than swallows."""
    import ast
    return ast.parse(recipe_source(), filename=SUBMISSION)


def module_level_functions():
    """name -> node for every function defined at module level, in source order."""
    import ast
    out = {}
    try:
        tree = recipe_ast()
    except (OSError, SyntaxError):
        return out
    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            out[node.name] = node
    return out


def build_signature():
    """(positional parameter names, node) for the module-level build, else (None, None)."""
    node = module_level_functions().get("build")
    if node is None:
        return None, None
    args = node.args
    return [p.arg for p in list(args.posonlyargs) + list(args.args)], node


def frozen_trainer_imports():
    """Lines where the recipe imports the frozen trainer package. The shard is the only channel."""
    import ast
    try:
        tree = recipe_ast()
    except (OSError, SyntaxError):
        return []
    hits = []
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            names = [a.name for a in node.names]
        elif isinstance(node, ast.ImportFrom):
            names = [node.module or ""]
        else:
            continue
        for name in names:
            if name == FROZEN_PACKAGE or name.startswith(FROZEN_PACKAGE + "."):
                hits.append([getattr(node, "lineno", 0), name])
    return hits



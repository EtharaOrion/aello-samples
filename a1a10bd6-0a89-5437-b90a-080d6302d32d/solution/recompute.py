def capture_times():
    """source id -> capture timestamp, held VERIFIER-SIDE.

    C3-LEAK re-derives the boundary decision from this table rather than from the timestamp the
    recipe wrote into its own manifest. A recipe that mislabels its rows must not be able to
    relabel its way past the one red line the task has zero tolerance for.
    """
    import csv
    path = heldout(CAPTURE_TIMES)
    if not os.path.exists(path):
        return {}
    try:
        with open(path, newline="") as handle:
            return dict((str(r.get("image_id")), str(r.get("capture_timestamp")))
                        for r in csv.DictReader(handle))
    except Exception:
        return {}


def boundary_instant():
    """The declared boundary, as an ISO-8601 instant.

    Timestamps are compared as STRINGS. ISO-8601 in a fixed zone with fixed field widths orders
    lexicographically, which keeps the comparison free of a timezone library the verifier
    environment may not carry. Phase 1 must emit both tables in that form.
    """
    path = heldout(BOUNDARY)
    if not os.path.exists(path):
        return None
    try:
        with open(path) as handle:
            return json.load(handle).get("boundary")
    except Exception:
        return None


def last_reward_log_entry():
    """The final parseable record of the agent's own reward_log.jsonl, or None."""
    path = run_record().get("reward_log")
    if not path or not os.path.exists(str(path)):
        return None
    last = None
    try:
        with open(str(path)) as handle:
            for line in handle:
                line = line.strip()
                if not line:
                    continue
                try:
                    row = json.loads(line)
                except Exception:
                    continue
                if isinstance(row, dict):
                    last = row
    except Exception:
        return None
    return last



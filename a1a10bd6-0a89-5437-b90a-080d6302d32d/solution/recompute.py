def measure():
    """Macro-averaged balanced accuracy: mean per-class RECALL over the twelve classes.

    Recall per class, then a flat mean over classes -- not overall accuracy. The distinction is
    the whole point of the metric: the eleven-species-plus-empty vocabulary is heavily skewed, so
    a shard that raises overall accuracy by dropping the rare classes lowers this number.
    """
    predicted, truth = graded_predictions(), private_a_labels()
    if not len(predicted) or not len(truth):
        raise ConstantUnmeasured("the graded prediction vector or its private labels are absent")
    n = min(len(predicted), len(truth))
    predicted, truth = predicted[:n], truth[:n]
    recalls = []
    for label in range(CLASS_COUNT):
        support = truth == label
        if not support.any():
            raise ConstantUnmeasured("class %s has no support on private_A" % label)
        recalls.append(float((predicted[support] == label).mean()))
    return float(sum(recalls) / len(recalls))

def numbers_equal(a, b):
    """Front-end constants compare by value: 10 and 10.0 are the same frame shift, and 10 and
    12.5 are the failure this whole slot is built around."""
    if isinstance(a, bool) or isinstance(b, bool):
        return a is b
    if isinstance(a, (int, float)) and isinstance(b, (int, float)):
        return abs(float(a) - float(b)) <= 1e-9
    return a == b


def symbol_tokens(symbol):
    """Split an operator or key name into tokens, so `lm` matches `lm_weight` and never `mel`."""
    return {t for t in re.split(r"[^a-z0-9]+", str(symbol).lower()) if t}


def forbidden_hits(symbols):
    banned = set(FORBIDDEN_DECODE_SYMBOLS)
    return sorted({s for s in symbols if symbol_tokens(s) & banned})


def last_reward_log_record():
    """The agent's own channel. Read here and nowhere else, and only to be contradicted."""
    path = run_record().get("reward_log")
    if not isinstance(path, str) or not path:
        return None
    resolved = path if os.path.isabs(path) else bundle(path)
    if not os.path.exists(resolved):
        return None
    last = None
    try:
        with open(resolved) as handle:
            for line in handle:
                line = line.strip()
                if not line:
                    continue
                parsed = json.loads(line)
                if isinstance(parsed, dict):
                    last = parsed
    except Exception:
        return None
    return last


def measure():
    """The binding per-corpus quality, on a higher-is-better axis.

    The reward map is a PRODUCT over the read-speech axis and the volunteer-speech axis, so the
    worse corpus binds and the graded quantity is min(1 - WER) across the two. Both values come
    from the harness's own measurement of the frozen export's greedy hypotheses under the pinned
    normalizer; nothing the agent reports enters here.
    """
    if not run_record():
        raise ConstantUnmeasured("the harness produced no run record, so no word error rate has "
                                 "been measured for this slot yet")
    qualities = []
    for shard in (LS_A, CV):
        wer = wer_value(shard)
        # An export that decoded nothing is NOT an unmeasured slot: it is the worst anchor, which
        # the contract fixes at WER 1.000 on both shards.
        qualities.append(1.0 - (1.0 if wer is None else float(wer)))
    return min(qualities)

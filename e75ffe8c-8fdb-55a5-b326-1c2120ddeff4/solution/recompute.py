def validate(grounding):
    """Refuse on a malformed derivation source rather than emitting a checker from one.

    The family validator that stood here asserted one thing -- that some item evaluated the run
    record -- which was true of a bundle whose every obligation item graded nothing. These are the
    invariants the emitted checker actually depends on.
    """
    problems = []
    items = grounding.get("items") or []
    if not items:
        problems.append("no items to compile")
    seen = set()
    for item in items:
        iid = item.get("id", "<unnamed>")
        if iid in seen:
            problems.append("duplicate item id %r" % iid)
        seen.add(iid)
        if set(item) != ITEM_SCHEMA:
            problems.append("item %r does not carry the closed schema: %s"
                            % (iid, sorted(set(item) ^ ITEM_SCHEMA)))
            continue
        if item["outcome_class"] not in OUTCOME_CLASSES:
            problems.append("item %r has outcome_class %r" % (iid, item["outcome_class"]))
        if item["evaluation_target"] not in grounding["evaluation_target_vocabulary"]:
            problems.append("item %r evaluates %r, which the vocabulary does not admit"
                            % (iid, item["evaluation_target"]))
        if not isinstance(item["weight"], int) or item["weight"] <= 0:
            problems.append("item %r carries weight %r" % (iid, item["weight"]))

    outcome = [i["id"] for i in items if i.get("dimension") == "outcome"]
    if len(outcome) != 1:
        problems.append("expected exactly one outcome item, found %r" % outcome)

    # A timed axis is graded on harness measurement, never on a self-reported duration.
    targets = {i.get("evaluation_target") for i in items}
    if "run_record" not in targets:
        problems.append("a timed slot must grade against the harness run record")

    for name in RAMP:
        if grounding["constants"].get(name) is not None:
            problems.append("constant %r is authored at Phase 0; it is measured, not authored"
                            % name)

    if grounding["deliverable"].get("kind") != "streaming_ctc_export":
        problems.append("the graded deliverable of this slot is a loadable streaming export, "
                        "not %r" % grounding["deliverable"].get("kind"))

    layout = grounding.get("corpus_layout") or {}
    bounds = layout.get("bounds") or {}

    # The frame count and the millisecond bound must be the SAME bound. If they drift apart, a
    # submission is measured against whichever of the two the check happens to read.
    frames, shift, span = (bounds.get("right_context_frames"), bounds.get("frame_shift_ms"),
                           bounds.get("right_context_ms"))
    if not all(isinstance(v, (int, float)) for v in (frames, shift, span)):
        problems.append("the right-context bound is not fully declared in corpus_layout bounds")
    elif abs(frames * shift - span) > 1e-9:
        problems.append("right_context_frames %r at frame_shift_ms %r is %r ms, not the declared "
                        "%r ms" % (frames, shift, frames * shift, span))

    envelope = set(layout.get("operator_envelope") or [])
    stray = sorted(set(layout.get("required_frontend_ops") or []) - envelope)
    if stray:
        problems.append("required_frontend_ops names %s, which the operator envelope does not"
                        % stray)
    if not envelope:
        problems.append("the operator envelope is empty, so no export could ever be refused")

    collapse = layout.get("collapse_order") or []
    if len(collapse) != 2 or len(set(collapse)) != 2:
        problems.append("collapse_order must name two distinct CTC steps, not %r" % (collapse,))

    if layout.get("statistics_reestimation_op") in set(layout.get("parameter_edit_ops") or []):
        problems.append("the statistics re-estimation op is also listed as a parameter edit op, "
                        "so the ordering check would compare an op against itself")

    for key in ("graded_shards", "wer_fields", "frontend_fields", "guarded_prefixes",
                "forbidden_decode_symbols"):
        if not layout.get(key):
            problems.append("corpus_layout %s is empty" % key)

    for key in ("sibling_shard_gap_bound", "permutation_reward_tau",
                "log_elapsed_tolerance_fraction"):
        value = bounds.get(key)
        if not isinstance(value, float) or not 0.0 < value <= 1.0:
            problems.append("corpus_layout bound %s is %r, which is not a fraction in (0,1]"
                            % (key, value))
    return problems



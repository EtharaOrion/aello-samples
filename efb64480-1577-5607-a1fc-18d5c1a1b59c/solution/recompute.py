def sparse_labelled_support():
    """How many pixels the shipped sparse annotation actually labels.

    This is the bound the agent's declared consumption is measured against, and it is counted from
    the delivered shard rather than read from an authored constant, so the check and the corpus
    cannot drift apart. None when the shard has not landed.
    """
    path = shipped("sparse_labels.npz")
    if not os.path.exists(path):
        return None
    import numpy as np
    archive = np.load(path, allow_pickle=False)
    return int(sum(int((np.asarray(archive[name]) != IGNORE).sum()) for name in archive.files))


def class_ids(mask):
    """The distinct class ids one scene mask carries, as plain ints.

    Every numpy call lives in this module's helpers rather than in a check body, so a check reads
    as the assertion it makes and an unreadable archive surfaces once, at load, with one reason.
    """
    import numpy as np
    return [int(v) for v in np.unique(mask)]


def predicted_classes(members):
    """Distinct class ids across the whole archive, with the ignore sentinel removed."""
    seen = set()
    for name in sorted(members):
        seen.update(class_ids(members[name]))
    seen.discard(IGNORE)
    return seen


def graded_pairs():
    """Each graded image id with its submitted mask and the private dense mask beside it."""
    import numpy as np
    submitted = load_submission()
    truth = np.load(heldout("graded_masks.npz"), allow_pickle=False)
    for name in sorted(truth.files):
        if str(name) in submitted:
            yield str(name), submitted[str(name)], np.asarray(truth[name])


def measure():
    """Mean IoU accumulated PER CLASS across the whole split, then averaged over classes present.

    Per class over the split, not per image and then over images: a scene holding two classes
    would otherwise weigh as much as a scene holding forty, and the long tail is the whole point
    of this axis. Pixels the private mask marks with the ignore sentinel enter neither accumulator,
    because the corpus does not claim a class for them and nothing should be scored on them.
    """
    import numpy as np
    intersection = [0] * NUM_CLASSES
    union = [0] * NUM_CLASSES
    for name, predicted, truth in graded_pairs():
        if predicted.shape != truth.shape:
            continue
        scored = truth != IGNORE
        p = predicted[scored]
        t = truth[scored]
        for label in set(int(v) for v in np.unique(t)) | set(int(v) for v in np.unique(p)):
            if not 0 <= label < NUM_CLASSES:
                continue
            hit = p == label
            want = t == label
            intersection[label] += int((hit & want).sum())
            union[label] += int((hit | want).sum())
    present = [intersection[k] / union[k] for k in range(NUM_CLASSES) if union[k]]
    if not present:
        raise ConstantUnmeasured("no graded scene produced a defined per-class IoU")
    return float(sum(present) / len(present))



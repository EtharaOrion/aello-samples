def load_submission():
    """One integer mask per graded scene, keyed by ADE20K image id.

    Strict at load, so every later check reads a mask rather than re-deciding what a mask is. A
    float or boolean array is not a mask; a three-dimensional member is a probability volume and
    is NOT silently argmaxed here, because choosing the class axis for the agent would be scoring
    a submission the agent did not make.
    """
    import numpy as np
    archive = np.load(SUBMISSION, allow_pickle=False)
    members = {}
    for name in archive.files:
        mask = np.asarray(archive[name])
        if mask.ndim != 2:
            raise ValueError("member %s has ndim %d; a scene mask is 2-D" % (name, mask.ndim))
        if mask.dtype.kind not in ("i", "u"):
            raise ValueError("member %s has dtype %s; a class id is an integer"
                             % (name, mask.dtype))
        members[str(name)] = mask
    if not members:
        raise ValueError("archive carries no members; no graded scene can be scored from nothing")
    return members



def load_submission():
    """The scored box lists: one per graded image id, under the `detections` member."""
    with open(SUBMISSION) as handle:
        doc = json.load(handle)
    if not isinstance(doc, dict):
        raise ValueError("the deliverable must be a JSON object, not a %s" % type(doc).__name__)
    table = doc.get("detections")
    if not isinstance(table, dict):
        raise ValueError("the deliverable carries no `detections` object keyed by image id")
    if not table:
        raise ValueError("`detections` names no graded image")
    return dict((str(image), entry) for image, entry in table.items())


def describe(table):
    return ",".join("%s:%d" % (image, len(table[image]) if isinstance(table[image], list) else -1)
                    for image in sorted(table)[:4])


def json_index(path):
    """One shipped index as an image-keyed mapping; empty when it will not read.

    Empty covers two cases and the checks distinguish them by what else is available: the index
    has not landed in this tree, or it landed and no longer parses. The second is a write into a
    guarded path happening in front of the verifier, so it must produce a report rather than an
    unhandled traceback -- an index that will not open is a finding, not a crash.
    """
    if not os.path.exists(path):
        return {}
    try:
        with open(path) as handle:
            doc = json.load(handle)
    except Exception:
        return {}
    return dict((str(k), v) for k, v in doc.items()) if isinstance(doc, dict) else {}



"""Derivation for AELLO-C8-S6: every canonical artifact descends from solution/grounding.yaml.

WHAT THIS GENERATOR EMITS AND WHY IT LOOKS LIKE THIS. The checks below are written about ONE
graded object: a scored box list per image, graded by the correct-localisation rate at a single
hard IoU of 0.5, learned from a fixed small fraction of training images that carry a box. That
metric is a per-image binary decided by the single highest-scoring box, so the emitted checker
walks per-image box lists, resolves each list's top box, tests it against that image's own native
pixel frame, and refuses a list whose top score is tied -- because a tie hands the graded binary
to serialisation order. None of that means anything on a segmenter, a classifier, a forecaster or
a retrieval chain: they have no top-1 box, no per-image cliff at 0.5, and no supervision fraction
to confine a run to.

The paths, the pixel-frame convention, the trimap tokens and the IoU threshold the emitted checks
read live in grounding.yaml's corpus_layout block and are substituted into the emitted prelude, so
the derivation source really is the source and this generator holds no corpus fact of its own.

Every compiled item carries a hand-written body. There is no generic fallback: an item without a
body is a REFUSAL, because the fallback this generator used to carry looked up an obligation
record that nothing writes, and a check that consults nothing passes for the wrong reason.
"""

def validate(grounding):
    """Refuse on a malformed derivation source rather than emitting from one.

    The family validator that stood here returned an empty list unconditionally, which is a check
    that consults nothing. These are the invariants the emitted checker actually depends on:
    without them a bad grounding produces a checker that imports and grades the wrong thing.
    """
    problems = []
    items = grounding.get("items") or []
    if not items:
        problems.append("no items to compile")
    seen = set()
    for item in items:
        iid = item.get("id", "<unnamed>")
        if iid in seen:
            problems.append("duplicate item id %r" % iid)
        seen.add(iid)
        if set(item) != ITEM_SCHEMA:
            problems.append("item %r does not carry the closed schema: %s"
                            % (iid, sorted(set(item) ^ ITEM_SCHEMA)))
            continue
        if item["outcome_class"] not in OUTCOME_CLASSES:
            problems.append("item %r has outcome_class %r" % (iid, item["outcome_class"]))
        if item["evaluation_target"] not in grounding["evaluation_target_vocabulary"]:
            problems.append("item %r evaluates %r, which the vocabulary does not admit"
                            % (iid, item["evaluation_target"]))
        if not isinstance(item["weight"], int) or item["weight"] <= 0:
            problems.append("item %r carries weight %r" % (iid, item["weight"]))
    outcome = [i["id"] for i in items if i.get("dimension") == "outcome"]
    if len(outcome) != 1:
        problems.append("expected exactly one outcome item, found %r" % outcome)
    for name in RAMP:
        if grounding["constants"].get(name) is not None:
            problems.append("constant %r is authored at Phase 0; it is measured, not authored"
                            % name)
    layout = grounding.get("corpus_layout") or {}
    for key in LAYOUT_KEYS:
        if key not in layout:
            problems.append("corpus_layout does not name %r, which the emitted checker reads"
                            % key)
    # The metric's own threshold is authored; a knee or a floor smuggled in as an IoU is not.
    threshold = layout.get("iou_threshold")
    if not isinstance(threshold, float) or not 0.0 < threshold < 1.0:
        problems.append("iou_threshold %r is not a threshold in (0, 1)" % (threshold,))
    if list(layout.get("box_order") or []) != ["x1", "y1", "x2", "y2"]:
        problems.append("box_order %r is not the published corner order"
                        % (layout.get("box_order"),))
    if not layout.get("trimap_tokens"):
        problems.append("corpus_layout names no trimap token, so the withheld dense supervision "
                        "cannot be recognised in a read declaration")
    if not layout.get("guarded_writes"):
        problems.append("corpus_layout names no guarded write path, so red line 2 is unstatable")
    return problems


def main():
    g = load_grounding()
    # The validator runs FIRST and refuses rather than emitting: a generator that writes a carrier
    # it knows is malformed hands the drift check a moving target.
    problems = validate(g)
    if problems:
        raise SystemExit("AELLO-C8-S6 grounding is not well-formed: " + "; ".join(problems))

    layout = g["corpus_layout"]
    outcome_id = [i["id"] for i in g["items"] if i["dimension"] == "outcome"][0]
    subst = {"slot_id": SLOT_ID, "path": g["deliverable"]["path"], "outcome_id": outcome_id,
             "graded_image_index": layout["graded_image_index"],
             "labelled_box_index": layout["labelled_box_index"],
             "training_image_index": layout["training_image_index"],
             "graded_boxes": layout["graded_boxes"],
             "withheld_trimap_dir": layout["withheld_trimap_dir"],
             "run_record": layout["run_record"],
             "iou": float(layout["iou_threshold"]),
             "box_order": tuple(layout["box_order"]),
             "trimap_tokens": tuple(layout["trimap_tokens"]),
             "guarded_writes": tuple(layout["guarded_writes"])}

    # EVERY compiled item carries a written body. The generic obligation lookup that used to stand
    # here is gone: it consulted a run-record key nothing writes, so an item that fell through to
    # it graded nothing at all and said so in no report.
    bodies = dict(BODIES)
    for it in g["items"]:
        if it["mode"] == "compiled" and it["id"] not in bodies:
            raise SystemExit("AELLO-C8-S6: no body written for compiled item %r; the generator "
                             "refuses rather than emitting a check that consults nothing"
                             % it["id"])
    # The outcome check must SAY the slot is unmeasurable before it reads anything. Reading the
    # submission first lets a missing-file failure mask the unmeasured signal, and the verifier
    # then reports gradeable=true with r_det=0.0 -- which seed/build/freeze_batch.py refuses.
    statements = [ln.strip() for ln in bodies[outcome_id].splitlines()
                  if ln.strip() and not ln.strip().startswith("#")]
    if not statements or statements[0] != REQUIRE_FIRST:
        raise SystemExit("AELLO-C8-S6: %r must call require_measured as its first statement, "
                         "before it reads the submission" % outcome_id)

    tests_dir = os.path.join(BUNDLE, "tests")
    os.makedirs(tests_dir, exist_ok=True)

    # solution/TRUTH.md and solution/rubrics.json are PRIVATE_CARRIERS: seed/identity.py plants a
    # canary block into them at freeze, and canary normalisation is what keeps planting from
    # moving identity. A generator that rewrote them plainly would DROP the planted tripwire, and
    # the next content_hash would differ from the frozen one. So the planted block is carried
    # across the regeneration rather than recreated.
    truth_path = os.path.join(HERE, "TRUTH.md")
    truth = build_truth(g, TITLE).rstrip("\n") + "\n"
    keep = None
    if os.path.exists(truth_path):
        import re as _re
        m = _re.search(r"<!-- AELLO-CANARY-BLOCK.*?-->\n?", open(truth_path).read(), _re.S)
        keep = m.group(0) if m else None
    with open(truth_path, "w") as fh:
        fh.write(truth + ("\n" + keep if keep else ""))

    rub_path = os.path.join(HERE, "rubrics.json")
    rub = build_rubrics(g, ITEM_KEYS)
    if os.path.exists(rub_path):
        try:
            prev = json.load(open(rub_path))
            if "canary" in prev:
                rub["canary"] = prev["canary"]
        except Exception:
            pass
    with open(rub_path, "w") as fh:
        json.dump(rub, fh, indent=1, sort_keys=True)
        fh.write("\n")
    with open(os.path.join(tests_dir, "rubrics.json"), "w") as fh:
        json.dump(build_rubrics(g, ITEM_KEYS), fh, indent=1, sort_keys=True)
        fh.write("\n")
    with open(os.path.join(tests_dir, "test_output.py"), "w") as fh:
        # The tail arrives FINAL and is NOT substituted: it is written against the emitted
        # prelude's names, it has already resolved every placeholder it owns, and it legitimately
        # carries percent formatting of its own, so formatting it a second time raises TypeError.
        # Only the prelude is substituted.
        fh.write(build_tests(g, PRELUDE % subst, bodies) + TAIL)
    with open(os.path.join(tests_dir, "constants.json"), "w") as fh:
        json.dump(g["constants"], fh, indent=1, sort_keys=True)
        fh.write("\n")
    # ORDER MATTERS. `with open(path, "w")` truncates BEFORE its body's arguments are evaluated,
    # so calling read_identity() inside the with-statement reads the file this line just emptied
    # and writes nulls over the frozen identity. Read first, then open.
    prov = build_provenance(g, read_identity(HERE))
    with open(os.path.join(HERE, "provenance.yaml"), "w") as fh:
        # MATCH seed/build/screen_bind.py and the frozen generators exactly: sort_keys=True,
        # default_flow_style=False, width=100. The screen writes this carrier after the freeze, so
        # a generator using a different dump convention reorders the keys on the next
        # regeneration and reports as drift even though no value changed.
        yaml.safe_dump(prov, fh, sort_keys=True, default_flow_style=False, width=100,
                       allow_unicode=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
